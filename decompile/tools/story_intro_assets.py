#!/usr/bin/env python3
"""EVENT_0100 traffic from its original 2d/34/56 bindings, not stage props.

Nine source hierarchies share two 1,200-frame CNK clips; thirty instances
select their own source frame offsets. World choreography remains in EVENT.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
import tempfile

ROOT=Path(__file__).resolve().parents[2]
DEC=ROOT/'decompile'
BASE=0x8c900000

def manifest():
    source=next((DEC/'afs/EVENT').glob('*_event_0100.bin'))
    texture=next((DEC/'afs/EVENT').glob('*_event_0100txr.bin'))
    data=source.read_bytes();txr=texture.read_bytes()
    def u(a):
        assert BASE<=a<=BASE+len(data)-4 and not a&3,hex(a)
        return struct.unpack_from('<I',data,a-BASE)[0]
    def commands(p):
        for _ in range(1024):
            words=tuple(u(p+j*4) for j in range(5));yield words
            if words[0]==100:return
            p+=20
        raise ValueError('unterminated EVENT stream')
    offsets={};at=0
    # Walk chunk lengths: GBIX can also occur inside compressed pixels.
    while at<len(txr):
        assert txr[at:at+4]==b'GBIX'
        offsets[at]=len(offsets)
        pvr=at+8+struct.unpack_from('<I',txr,at+4)[0]
        assert txr[pvr:pvr+4]==b'PVRT'
        at=pvr+8+struct.unpack_from('<I',txr,pvr+4)[0]
    setup=list(commands(u(BASE)));main=list(commands(u(BASE+4)))
    table=next(w[1] for w in setup if w[0]==0x56);lists={}
    while u(table):
        tl,ptr=u(table),u(table+4);count=u(tl+4)
        assert count==1
        lists[tl]=[offsets[u(ptr)-0x8cda0000]];table+=8
    models=[];instances=[]
    motions=list(dict.fromkeys(w[2] for w in main if w[0]==0x34))
    assert len(motions)==2 and all(u(p)==0x04b00011 for p in motions)
    for w in main:
        if w[0]!=0x2d:continue
        slot,root,tl,flags=w[1:];assert flags==2
        model=next((i for i,r in enumerate(models) if r['root']==root and r['texlist']==tl),len(models))
        if model==len(models):models.append(dict(root=root,texlist=tl,texture_map=lists[tl],motions=motions))
        motion=next(q for q in main if q[0]==0x34 and q[1]==slot)
        instances.append(dict(slot=slot,model=model,motion=motions.index(motion[2]),frame=motion[3]))
    assert len(models)==9 and len(instances)==30
    return dict(descriptor=7,source=str(source.relative_to(DEC)),textures=str(texture.relative_to(DEC)),
                source_sha256=hashlib.sha256(data).hexdigest(),textures_sha256=hashlib.sha256(txr).hexdigest(),
                models=models,instances=instances)

def export(path):
    info=manifest()
    args=[sys.executable,str(DEC/'tools/jgc_convert.py'),str(path),'--motions=2',
          '--source-material=1','--source-environment=1']
    for i,r in enumerate(info['models']):
        args.append(f"intro_traffic_{i}:{info['source']}:{info['textures']}:0,0,0,0:rawat:8c900000:{r['root']:x}:"
                    +','.join(f'{m:x}' for m in r['motions'])+':texmap='+','.join(map(str,r['texture_map'])))
    subprocess.run(args,cwd=DEC,check=True)
    return info

def bindings(info):
    rows=['/* Generated by story_intro_assets.py: EVENT_0100 opcode 2d/34. */',
          'static const struct { unsigned root, texlist; } INTRO7_MODELS[9] = {']
    rows += [f"    {{0x{r['root']:08x}u,0x{r['texlist']:08x}u}}," for r in info['models']]
    rows += ['};','static const unsigned INTRO7_MOTIONS[2] = {'+
             ','.join(f'0x{m:08x}u' for m in info['models'][0]['motions'])+'};','']
    return '\n'.join(rows)

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    output=ROOT/'psp/scene0100.jgc';header=ROOT/'psp/src/story_intro_tables.inc'
    if args.check:
        with tempfile.TemporaryDirectory(prefix='jgr-story-intro-assets-') as tmp:
            p=Path(tmp)/output.name;info=export(p)
            assert p.read_bytes()==output.read_bytes()
            assert json.loads(output.with_suffix('.json').read_text())==info
            assert header.read_text()==bindings(info)
    else:
        info=export(output);output.with_suffix('.json').write_text(json.dumps(info,indent=2)+'\n')
        header.write_text(bindings(info))

if __name__=='__main__':main()
