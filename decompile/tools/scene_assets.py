#!/usr/bin/env python3
"""Package original EVENT images and source-bind EVENT_5056's custom actor.

The archive is SCN1 + count + 20-byte {id,flags,base,offset,length} records.
Images are unmodified, including all three command streams and NJS tracks.
Only audited runtime routes are enabled by the game; having an image in this
archive does not imply its opcodes, actors, or audio are implemented.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
import tempfile
from cutscene_sources import event_descriptors

DEC=Path(__file__).resolve().parents[1]
PSP=DEC.parent/'psp'

def sources():
    exe=(DEC/'extracted/1ST_READ.BIN').read_bytes()
    def u(a):return struct.unpack_from('<I',exe,a-0x8c010000)[0]
    entries=event_descriptors()
    offset=8+112*20;table=bytearray(112*20);images=bytearray();manifest=[]
    stored={}
    for entry in entries:
        i,flags,name=entry['id'],entry['flags'],entry['name']
        data=(DEC/entry['source']).read_bytes()
        # S variants share the loader's exact image, while retaining their
        # own descriptor flags. No name-based alias or duplicate payload.
        if entry['source_index'] not in stored:
            stored[entry['source_index']]=offset+len(images);images+=data
        struct.pack_into('<5I',table,i*20,i,flags,0x8c900000,stored[entry['source_index']],len(data))
        manifest.append(dict(entry,length=len(data),sha256=hashlib.sha256(data).hexdigest()))
    lines=['/* Generated by scene_assets.py: 08b7ac -> 10a808, PLAY frame counts. */',
           'static const short SCENE_CLIP[170] = {'+','.join(str(u(0x8c10a808+i*16)) for i in range(170))+'};',
           'static const unsigned short SCENE_FRAMES[16][176] = {']
    bank=(PSP/'chars.jgc').read_bytes();h=struct.unpack_from('<16I',bank,4)
    for model in (4,6,3,2,1,7,10,0,15,8,13,11,12,5,9,14):
        _,_,m,n=struct.unpack_from('<4I',bank,h[7]+model*48);assert n==176
        lines.append('{'+','.join(str(struct.unpack_from('<I',bank,h[13]+8*(m+j))[0]) for j in range(n))+'},')
    # 06fa40 type 3 -> 1b58a8: first root, first texlist. The texture-loader
    # table 1b79c8 binds its single slot to killertxr GBIX +0.
    assert u(u(0x8c06fb04)+12)==0x8c1b58a8
    root=u(u(0x8c1b58a8));tl=u(u(0x8c1b58a8+4))
    assert root==0x8ca02f24 and tl==0x8c1b7974 and u(tl+4)==1
    assert u(0x8c1b79c8)==tl and u(u(0x8c1b79cc))==0x8ca00000
    return b'SCN1'+struct.pack('<I',112)+table+images,manifest,'\n'.join(lines+['};',''])

def actor_bank(output):
    subprocess.run([sys.executable,str(DEC/'tools/jgc_convert.py'),str(output),'--motions=1',
        'scene_killer:afs/ENEMY/007_killerdat.bin:afs/ENEMY/006_killertxr.bin:0,0,0,0:rawat:8ca00000:8ca02f24:8c90126c:tex=0:motionimage=afs/EVENT/152_event_5056.bin@8c900000'],cwd=DEC,check=True)

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    archive,manifest,tables=sources()
    if args.check:
        assert (PSP/'scenes.bin').read_bytes()==archive
        assert json.loads((PSP/'scenes.json').read_text())==manifest
        assert (PSP/'src/scene_tables.inc').read_text()==tables
        with tempfile.TemporaryDirectory(prefix='jgr-scene-assets-') as tmp:
            path=Path(tmp)/'scene5056.jgc';actor_bank(path)
            assert path.read_bytes()==(PSP/'scene5056.jgc').read_bytes()
    else:
        (PSP/'scenes.bin').write_bytes(archive)
        (PSP/'scenes.json').write_text(json.dumps(manifest,indent=2)+'\n')
        (PSP/'src/scene_tables.inc').write_text(tables)
        actor_bank(PSP/'scene5056.jgc')
    print(f'{len(manifest)} EVENT descriptors, {len({r["source_index"] for r in manifest})} original images, {len(archive):,} bytes; source-bound 5056 actor/motion.')
if __name__=='__main__':main()
