#!/usr/bin/env python3
"""Recover PLAY local normals/materials without rebaking the shared JGC2 bank."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
import tempfile
ROOT=Path(__file__).resolve().parents[2]
def convert():
    original=(ROOT/'psp/chars.jgc').read_bytes()
    assert original[:4]==b'JGC2'
    with tempfile.TemporaryDirectory(prefix='jgr-player-light-') as directory:
        temp=Path(directory);model=temp/'chars.jgc';side=temp/'lighting.bin'
        subprocess.run([sys.executable,str(ROOT/'decompile/tools/jgc_convert.py'),str(model),
            '--spec=chars_spec.txt','--toon=1','--lighting-sidecar='+str(side)],
            cwd=ROOT/'decompile',check=True,stdout=subprocess.PIPE)
        recovered=model.read_bytes();data=side.read_bytes()
    nc,_,_,nv=struct.unpack_from('<4I',original,4)
    assert struct.unpack_from('<4I',original,4)==struct.unpack_from('<4I',recovered,4)
    a=struct.unpack_from('<9I',original,32);b=struct.unpack_from('<9I',recovered,32)
    # Skeleton, owner/batch ordering and exact source-local geometry must
    # match the bank used at runtime. Its existing colours/keys/pixels stay
    # untouched; they need not be regenerated by this companion exporter.
    assert original[a[0]:a[3]]==recovered[b[0]:b[3]]
    for i in range(nv):
        v=original[a[3]+i*28:a[3]+(i+1)*28];w=recovered[b[3]+i*28:b[3]+(i+1)*28]
        assert v[:8]+v[12:]==w[:8]+w[12:],('source vertex mismatch',i)
    assert len(data)==20+nv*20
    return data,{'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),
        'shared_bank_sha256':hashlib.sha256(original).hexdigest(),'vertices':nv,'models':nc,
        'source':'PLAYER PLAY/CNK normal, vertex-cache owner and material streams',
        'draw':'019cfc -> 0b8b1c mode 0 (cel); no change to original ignore-light hulls',
        'scope':'final-stage lighting only; shared bank remains unchanged',
        'byte_exact_rendering':False}
def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    data,manifest=convert();path=ROOT/'psp/playerlight.bin'
    if args.check:assert path.read_bytes()==data
    else:
        path.write_bytes(data)
        path.with_suffix('.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(json.dumps(manifest))
if __name__=='__main__':main()
