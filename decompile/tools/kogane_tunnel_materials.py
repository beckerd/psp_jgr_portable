#!/usr/bin/env python3
"""Restore CNK UseAlpha for Kogane's GBIX 20087 tunnel-floor atlas.

The legacy JGS writer ORs texture alpha into every strip. This atlas contains
transparent texels but the straight-channel strips explicitly draw opaque;
only the authored overlays use alpha. Keep the existing geometry/sidecar keys.
"""
import argparse
import collections
import json
from pathlib import Path
import struct
import ninjalib as nl
from stage_render_assets import Source, SB
from stage_visibility_assets import fnv
ROOT=Path(__file__).resolve().parents[2]

def build(assets=ROOT/'psp'):
    stage=(Path(assets)/'stage2.jgs').read_bytes()
    side=json.loads((Path(assets)/'stage2.jgs.map.json').read_text())
    mapping=json.loads((ROOT/'decompile/stage2_texmap.json').read_text())['texmap']
    source=Source(2);oo,ob,ov=struct.unpack_from('<3I',stage,28)
    groups=collections.defaultdict(list)
    for i,(off,kind,_) in enumerate(side):
        first,count=struct.unpack_from('<2I',stage,oo+i*32+16)
        batches=list(range(first,first+count))
        if any(struct.unpack_from('<H',stage,ob+j*16+12)[0]==59 for j in batches):
            groups[off,kind].append((i,batches))
    rows=[];nl.MAXEDGE=120
    for (off,kind),objects in groups.items():
        assert kind in ('proto','far')
        temp=nl.JgsBuilder()
        for node,matrix in nl.walk_tree(source.data,SB+off,SB,nl.placement_matrix((0,0,0),(0,0,0))):
            if not node['model'] or node['ev']&8:continue
            texmap=mapping.get(str(node['addr']-SB),mapping.get(str(off)))
            assert texmap
            temp.add_model(source.data,node['model'],SB,matrix,lambda slot:texmap[slot])
        cursor=0
        for oid,batches in objects:
            node=struct.unpack('<4f4I',temp.objs[cursor]);cursor=(cursor+1)%len(temp.objs)
            originals=temp.batches[node[4]:node[4]+node[5]]
            assert len(batches)==len(originals),(oid,len(batches),len(originals))
            for batch,original in zip(batches,originals):
                tex,flags=struct.unpack_from('<2H',stage,ob+batch*16+12)
                if tex!=59:continue
                assert original[4]==87,(oid,batch,original[4])
                rows.append(dict(object=oid,batch=batch,root=hex(SB+off),source_texture=87,alpha=bool(original[5]&1)))
    assert len(rows)==48, len(rows)
    opaque=[r['batch'] for r in rows if not r['alpha']]
    lines=['/* Generated by kogane_tunnel_materials.py; original CNK UseAlpha. */',
           '#define KOGANE_TUNNEL_STAGE_KEY 0x%08xu'%fnv(stage[:ov]),
           'static const unsigned short kogane_tunnel_opaque[]={'+','.join(map(str,opaque))+'};','']
    return '\n'.join(lines),rows

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true')
    parser.add_argument('--assets',type=Path,default=ROOT/'psp')
    parser.add_argument('--output',type=Path,default=ROOT/'psp/src/kogane_tunnel_materials.inc');args=parser.parse_args()
    header,rows=build(args.assets);path=args.output
    if args.check:assert path.read_text()==header
    else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(header)
    print(json.dumps(rows,indent=2))
