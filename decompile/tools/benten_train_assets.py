#!/usr/bin/env python3
"""Benten's dedicated 08df00 train: original model, sparse routes and colliders.

The train is not an opcode-9 traffic object. Boundary callbacks 08dda0 and
subway-sector controller 08de88 select four independent native NJS motions.
"""
import argparse, hashlib, json, struct, subprocess, sys, tempfile
from pathlib import Path
from stage_render_assets import Source, EB, SB, tree, IDENTITY
ROOT=Path(__file__).resolve().parents[2]; DEC=ROOT/'decompile'; BASE=0x10000000
MOTIONS=(0x8cdb5360,0x8cdc36cc,0x8cdc8d68,0x8cdcdef4)
MODEL=0x8ccce8dc; TEXLIST=0x8c1c2c68
def generate(out):
    s=Source(3);image=bytearray(16);cache={}
    def append(blob):
        blob=bytes(blob)
        if blob in cache:return cache[blob]
        image.extend(bytes(-len(image)%4));a=BASE+len(image);image.extend(blob);cache[blob]=a;return a
    def raw(a,n):return s.image[a-EB:a-EB+n]
    motions=[];wrap_motion=0
    for a in MOTIONS:
        md,frames,kind=s.words(a,3);assert kind==0x20003
        entries=[]
        for b in range(4):
            p,q,n,m=s.words(md+b*16,4)
            # Route 2, car 3 declares 138 rotation keys, but the original
            # linear search reads its adjacent 139th key (frame 889).
            # Preserve that real key and the declared-count wrap separately.
            if a==MOTIONS[2] and b==2:
                assert m==138 and s.words(q+m*16)[0]==frames-1
                m+=1
            entries.extend((append(raw(p,n*16)) if p else 0,append(raw(q,m*16)) if q else 0,n,m))
        motions.append(append(struct.pack('<3I',append(struct.pack('<16I',*entries)),frames,kind)))
        if a==MOTIONS[2]:
            entries[11]=138
            wrap_motion=append(struct.pack('<3I',append(struct.pack('<16I',*entries)),frames,kind))
    (out/'benten_train.bin').write_bytes(struct.pack('<4s7I',b'BTR1',BASE,len(image),*motions,wrap_motion)+image)
    def f(x):return float(x).hex()+'f'
    def vec(v):return '{'+','.join(f(x) for x in v)+'}'
    lines=['/* Generated by benten_train_assets.py from the US Dreamcast. */']
    selectors=[struct.unpack_from('<If',s.image,0x8c1b9c60-EB+i*8) for i in range(8)]
    lines+=['static const unsigned train_selectors[8][2]={'+','.join('{%d,%d}'%(a,b) for a,b in selectors)+'};']
    lines+=['static const MissionQuad train_boundaries[5]={']
    for i in (5,6,7,8,13):
        a=s.words(s.words(0x8c031e00)[0]+i*4)[0];flags=s.words(a)[0]
        v=struct.unpack_from('<15f',s.image,a+4-EB)
        lines+=['{%du,{%s},%s,{0},0},'%(flags,','.join(vec(v[j:j+3]) for j in range(0,12,3)),vec(v[12:15]))]
    lines+=['};','static const TrainBody train_bodies[4]={']
    def nodes(a,parent=-1):
        result=[]
        while a:
            ix=len(result);kind,flags,mesh=struct.unpack_from('<HHI',s.image,a-EB)
            result.append((a,parent,kind,flags,mesh))
            child,sib=s.words(a+60,2)
            assert not child or parent==-1
            if child:result+=nodes(child,ix)
            a=sib
        return result
    for a,parent,kind,flags,mesh in nodes(0x8cd75300):
        assert (kind,flags)==(4,24)
        pose=struct.unpack_from('<3f3i3f',s.image,a+12-EB)
        lines+=['{%d,%s,{%s},%s,%s,%s},'%(parent,vec(pose[:3]),','.join(map(str,pose[3:6])),vec(pose[6:]),vec(struct.unpack_from('<24f',s.image,mesh-EB)),vec(struct.unpack_from('<3f',s.image,a+48-EB)))]
    lines+=['};'];totals=[]
    for variant,root in enumerate((0x8cd762fc,0x8cd76128)):
        tris=[]
        for bone,(a,parent,kind,flags,mesh) in enumerate(nodes(root)):
            assert kind in (0,6)
            if not kind:continue
            vb,pb,nv,np=struct.unpack_from('<IIHH',s.image,mesh-EB)
            for j in range(np):
                ix,fl,kinds=s.words(pb+j*36+24,3);n=fl&65535;ids=struct.unpack_from('<%dh'%(n+2),s.image,ix-EB)
                wind=bool(fl&0x40000000)
                for k in range(n):
                    order=(ids[k],ids[k+1 if wind else k+2],ids[k+2 if wind else k+1])
                    verts=[struct.unpack_from('<3f',s.image,vb+i*12-EB) for i in order]
                    tris.append((bone,verts,kinds>>16,kinds&65535,(1 if fl&0x80000000 else 0)|(0 if wind else 2)))
                    wind=not wind
        vertices=[];indices={};indexed=[]
        for bone,verts,surf,mask,dbl in tris:
            ids=[]
            for v in verts:
                key=(bone,struct.pack('<3f',*v))
                if key not in indices:indices[key]=len(vertices);vertices.append((bone,v))
                ids.append(indices[key])
            indexed.append((ids,surf,mask,dbl))
        lines+=['static const TrainVertex train_vertices%d[]={ '%variant]
        for bone,v in vertices:lines+=['{%du,%s},'%(bone,vec(v))]
        lines+=['};']
        totals.append(len(tris));lines+=['static const TrainTriangle train_surfaces%d[]={ '%variant]
        for ids,surf,mask,dbl in indexed:lines+=['{{%s},%du,%du,%du},'%(','.join(map(str,ids)),surf,mask,dbl)]
        lines+=['};']
    lights=[struct.unpack_from('<8f',s.exe,0x8c175d90+i*32-EB) for i in range(46)]
    lines+=['static const float train_lights[46][8]={']+[vec(v)+',' for v in lights]+['};','']
    (out/'benten_train_data.inc').write_text('\n'.join(lines))
    with tempfile.TemporaryDirectory(prefix='jgr-train-textures-') as tmp:
        tmfile=Path(tmp)/'textures.json'
        subprocess.run([sys.executable,'tools/static_texmap.py','extracted/1ST_READ.BIN','3',str(tmfile)],cwd=DEC,check=True,stdout=subprocess.DEVNULL)
        tm=json.loads(tmfile.read_text());tx=Path(tmp)/'textures.bin';tx.write_bytes(b''.join((DEC/p).read_bytes() for p in tm['packs']))
        mapping=tm['texlists'][str(TEXLIST)]
        row=f'train:afs/STAGE3/000_st3dat.bin:{tx}:0,0,0,0:rawat:{SB:x}:{MODEL:x}:0:texmap='+','.join(map(str,mapping))+':lighting=1:cull=none'
        subprocess.run([sys.executable,'tools/jgc_convert.py',str(out/'benten_train.jgc'),'--motions=0','--texmax=512','--source-material=1','--source-environment=1',row],cwd=DEC,check=True)
    side=json.loads((ROOT/'psp/stage3.jgs.map.json').read_text());assert MODEL-SB not in {v[0] for v in side}
    meta=dict(model=hex(MODEL),texlist=hex(TEXLIST),texture_indices=mapping,motions=[hex(a) for a in MOTIONS],selectors=selectors,
        triangles=totals,source_sha256=hashlib.sha256(s.data).hexdigest(),motion_bytes=len(image),
        source_functions=['08dda0','08de88','08df00','08e0f8','08e2fc','08e388'])
    (out/'benten_train_assets.json').write_text(json.dumps(meta,indent=2)+'\n')
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    with tempfile.TemporaryDirectory(prefix='jgr-train-export-') as tmp:
        out=Path(tmp);generate(out)
        for file in out.iterdir():
            dest=ROOT/'psp'/('src' if file.suffix=='.inc' else '')/file.name
            if a.check:assert dest.read_bytes()==file.read_bytes(),file.name
            else:dest.write_bytes(file.read_bytes())
if __name__=='__main__':main()
