#!/usr/bin/env python3
"""Eight source Shibuya hinged panels (types6..9), both authored NJS motions.

030688 -> 0e139c/0e1418/0e15ec. Type11 has a similar handler but zero
placements in the shipped STAGE1 lists, so no new placement is invented.
"""
# These owners use the original normal draw path 234fc6 / mode 1,
# which submits both face directions (unlike the PLAY cel-hull path).

import argparse,hashlib,json,struct,subprocess,sys,tempfile
from pathlib import Path
from city_opening_assets import body_boxes,ROOT,DEC
from stage_render_assets import Source,EB,SB
TYPES=(6,7,8,9)
MOTION_TABLE=((0x8c105e64,0x8c105e68),(0x8c105e70,0x8c105e6c),(0x8c105e78,0x8c105e74),(0x8c105e7c,0x8c105e80))
def generate(out):
    s=Source(1);rows=[];boxes=[];types=[];ranges=[]
    tmfile=out/'textures.json';subprocess.run([sys.executable,'tools/static_texmap.py','extracted/1ST_READ.BIN','1',str(tmfile)],cwd=DEC,check=True,stdout=subprocess.DEVNULL)
    tm=json.loads(tmfile.read_text());textures=out/'textures.bin';textures.write_bytes(b''.join((DEC/p).read_bytes() for p in tm['packs']))
    for ty,tables in zip(TYPES,MOTION_TABLE):
        root=s.words(0x8c107564+ty*4)[0];tl=s.words(0x8c1075d4+ty*4)[0];mapping=tm['texlists'][str(tl)]
        assert s.words(root+44,2)==(0,0)
        motions=[s.words(a)[0] for a in tables]
        for m in motions:
            md,frames,kind=s.words(m,3);assert (frames,kind)==(20,0x20003)
            ranges.extend(((m,m+12),(md,md+16)))
            p=s.words(md,4)
            for ch in range(2):
                if p[ch]:ranges.append((p[ch],p[ch]+16*p[ch+2]))
        boxes+=body_boxes(s,s.words(0x8c107644+ty*4)[0]);assert len(boxes)==len(types)+1
        rows.append(f'shibuyaDoor{ty}:afs/STAGE1/000_st1dat.bin:{textures}:0,0,0,0:rawat:{SB:x}:{root:x}:0:texmap='+','.join(map(str,mapping))+':lighting=1:cull=none')
        types.append(dict(type=ty,root=root,texlist=tl,texture_indices=mapping,motions=motions,frames=20))
    subprocess.run([sys.executable,'tools/jgc_convert.py',str(out/'shibuya_doors.jgc'),'--texmax=512','--source-material=1','--source-environment=1',*rows],cwd=DEC,check=True)
    base=min(a for a,b in ranges);end=max(b for a,b in ranges);raw=bytes(s.image[base-EB:end-EB])
    # Tiny original NJS image retained verbatim, including s32 angles.
    (out/'shibuya_doors.bin').write_bytes(struct.pack('<4sII',b'SDM1',base,len(raw))+raw)
    placements=[p for p in s.records(0x8c10618c,63,40,28) if p['pid'] in TYPES];assert len(placements)==8
    assert not [p for p in s.records(0x8c10618c,63,40,28) if p['pid']==11]
    stage=(ROOT/'psp/stage1.jgs').read_bytes();oo=struct.unpack_from('<I',stage,28)[0];side=json.loads((ROOT/'psp/stage1.jgs.map.json').read_text())
    baked=[i for i,v in enumerate(side) if v[0] in {t['root']-SB for t in types}];assert baked==list(range(773,781))
    visibility=(ROOT/'psp/stage1.jvo').read_bytes();no,nocc=struct.unpack_from('<2I',visibility,4)
    assert visibility[:4] in (b'JVO4',b'JVO5')
    blockers=set()
    for i in range(nocc):
        owner,packed=struct.unpack_from('<2H',visibility,36+no*24+i*80+76)
        blockers.add(owner)
        if visibility[:4]==b'JVO5' and packed>>3:blockers.add((packed>>3)-1)
    assert not set(baked)&blockers
    col=(ROOT/'psp/stage1.col').read_bytes();off=struct.unpack_from('<I',col,8)[0]
    _,world,np,ne=struct.unpack_from('<4I',col,off);off+=16+1028*4+np*32+ne*12
    magic,owners,_,_=struct.unpack_from('<4I',col,off);assert magic==0x31504943
    assert not {p['address'] for p in placements}&{struct.unpack_from('<I',col,off+16+16*i)[0] for i in range(owners)}
    def f(v):return float(v).hex()+'f'
    def arr(v):return '{'+','.join(f(x) for x in v)+'}'
    lines=['/* Original 030688 / 0e1418; generated by shibuya_door_assets.py. */','static const OpeningType shibuya_door_types[]={']
    for i,ty in enumerate(TYPES):lines.append(f'    {{{ty},OPENING_HINGED,20,{i},1,5,4}},')
    lines+=['};','static const unsigned shibuya_door_motions[4][2]={']
    lines += ['    {'+','.join(f'0x{a:08x}u' for a in t['motions'])+'},' for t in types]
    lines+=['};','static const OpeningBox shibuya_door_boxes[]={']
    for b in boxes:lines.append('    {'+arr([x for v in b['vertices'] for x in v])+','+arr(b['center'])+'},')
    lines+=['};','static const OpeningPlacement shibuya_door_placements[]={']
    for p in placements:lines.append('    {0x%08xu,%du,%du,%s,{%s},%s},'%(p['address'],TYPES.index(p['pid']),p['sector'],arr(p['pos']),','.join(map(str,p['ang'])),arr(p['scale'])))
    lines+=['};','static const OpeningBaked shibuya_door_baked[]={']
    for i in baked:
        obj=struct.unpack_from('<4f4I',stage,oo+i*32)
        lines.append('    {%du,{%s,%s}},'%(i,','.join(f(v) for v in obj[:4]),','.join(str(v)+'u' for v in obj[4:])))
    lines+=['};','static const float shibuya_door_lights[63][8]={']
    lines += [arr((1,1,1,-1,-.71,-1,.95,.47))+',' for _ in range(63)]
    lines+=['};',''];(out/'shibuya_door_data.inc').write_text('\n'.join(lines))
    (out/'shibuya_door_assets.json').write_text(json.dumps(dict(types=types,placements=placements,boxes=boxes,static_objects=baked,motion_base=base,motion_bytes=len(raw),
        source_sha256=hashlib.sha256(s.data).hexdigest(),model_sha256=hashlib.sha256((out/'shibuya_doors.jgc').read_bytes()).hexdigest(),motion_sha256=hashlib.sha256(raw).hexdigest()),indent=2)+'\n')
def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    with tempfile.TemporaryDirectory(prefix='jgr-shibuya-doors-') as tmp:
        p=Path(tmp);generate(p)
        for name in ('shibuya_doors.jgc','shibuya_doors.bin','shibuya_door_data.inc','shibuya_door_assets.json'):
            target=ROOT/'psp'/('src' if name.endswith('.inc') else '')/name
            if args.check:assert target.read_bytes()==(p/name).read_bytes(),name
            else:target.write_bytes((p/name).read_bytes())
if __name__=='__main__':main()
