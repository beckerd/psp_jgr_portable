#!/usr/bin/env python3
"""Original task 21d/220 SYSOPTION model lists and garage record strings."""
from pathlib import Path
import json
import struct
import subprocess
import sys
ROOT=Path(__file__).resolve().parents[2]
B=0x8cf00000
TABLES=(
 ('BOOK_OPEN',0x10e738,0x10e754),('BOOK_RETURN',0x10e770,0x10e784),
 ('BOOK_STATIC',0x10e798,0x10e7a8),('BOOK_SELECT',0x10e7b8,0x10e7cc),
 ('BOOK_BACK',0x10e7e0,0x10e7e8),
 ('RECORD_OPEN',0x1b9d08,0x1b9d50),('RECORD_BACK',0x1b9cf0,0x1b9cfc),
 ('RECORD_STORY',0x1b9dc8,0x1b9dec),('RECORD_JET',0x1b9dd8,0x1b9dec),
 ('RECORD_CITY',0x1b9d98,0x1b9db0),('RECORD_KIND',0x1b9e00,0x1b9e54),
 ('OPTION_BACK',0x1b9fa0,0x1b9fac),('OPTION_OPEN',0x1b9fb8,0x1b9fc8),
 ('OPTION_SOUND_OPEN',0x1b9fd8,0x1b9fe0),('OPTION_RUMBLE_OPEN',0x1b9fe8,0x1b9ff0),
 ('OPTION_VALUE_OPEN',0x1b9ff8,0x1ba000),('OPTION_RUMBLE_VALUE_OPEN',0x1ba008,0x1ba010),
 ('OPTION_SELECT',0x1ba018,0x1ba028),('OPTION_SOUND1',0x1ba038,0x1ba044),
 ('OPTION_SOUND0',0x1ba050,0x1ba05c),('OPTION_RUMBLE1',0x1ba068,0x1ba074),
 ('OPTION_RUMBLE0',0x1ba080,0x1ba08c))
def extract():
    ex=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    dat=(ROOT/'decompile/afs/U_SYSOPTION/001_sysoptiondat.bin').read_bytes()
    garage=(ROOT/'decompile/afs/U_GARAGE/001_garagedat.bin').read_bytes()
    u=lambda a:struct.unpack_from('<I',ex,(a&0xffffff)-0x10000)[0]
    v=lambda a:struct.unpack_from('<I',dat,a-B)[0]
    spec=[];entries={};lines=['/* Generated by record_book_assets.py from original US assets. */']
    def model(cell,motion):
        root=v(cell);mot=v(motion)if motion else 0
        key=(root,mot)
        if key not in entries:
            entries[key]=len(spec)
            spec.append(f'Book{len(spec)}:afs/U_SYSOPTION/001_sysoptiondat.bin:afs/U_SYSOPTION/002_sysoptiontxr.bin:0,0,0,0:rawat:{B:x}:{root:x}:{mot:x}')
        return entries[key],v(mot)>>16 if mot else 0
    for name,models,motions in TABLES:
        rows=[];k=0
        while u(models+k*4):
            cell,mot=u(models+k*4),u(motions+k*4)
            assert B<=cell<B+len(dat) and (not mot or B<=mot<B+len(dat))
            rows.append(model(cell,mot));k+=1;assert k<32
        lines.append(f'static const BookModel {name}[]={{'+','.join('{%d,%d}'%r for r in rows)+'};')
    for name,cell,mot in [('RECORD_DOWN',B+0x194,B+0x198),('RECORD_UP',B+0x19c,B+0x1a0)]:
        lines.append(f'static const BookModel {name}='+('{%d,%d};'%model(cell,mot)))
    # 09067c binds the single SYSOPTION portrait atlas (GBIX 527), then
    # dereferences the original resident-ID table. No PLAY/model-ID mapping.
    portraits=[model(u(0x1b9ea8+4*i),0) for i in range(15)]
    lines.append('static const BookModel RECORD_PORTRAIT[]={'+','.join('{%d,%d}'%r for r in portraits)+'};')
    for name,address,n,fmt in [('RECORD_SCROLL',0x1b9ee4,5,'f'),('RECORD_PAGE',0x1b9ef8,5,'i'),
                               ('RECORD_COLOR',0x1b9f20,6,'I'),('RECORD_PORTRAIT_XY',0x1b9f38,10,'f'),
                               ('RECORD_JET_XY',0x103040,10,'f'),('RECORD_STORY_XY',0x103068,10,'f'),
                               ('RECORD_SCORE_XY',0x103090,10,'f'),('RECORD_STORY_SCORE_XY',0x1030b8,2,'f'),
                               ('RECORD_PTS_XY',0x1030c0,10,'f'),('RECORD_STORY_PTS_XY',0x1030e8,2,'f'),
                               ('RECORD_SCORE_RIGHT',0x103120,5,'i'),('RECORD_JET_SCALE',0x103134,20,'f'),
                               ('RECORD_STORY_SCALE',0x103184,4,'f')]:
        val=struct.unpack_from('<'+str(n)+fmt,ex,address-0x10000)
        ty={'f':'float','i':'int','I':'unsigned'}[fmt]
        text=[x.hex()+'f' if fmt=='f' else f'0x{x:08x}u' if fmt=='I' else str(x)for x in val]
        lines.append(f'static const {ty} {name}[]={{'+','.join(text)+'};')
    gp=struct.unpack_from('<I',garage,0x34c)[0]-0x8c800000
    strings=[]
    for i in range(0x110//4):
        p=struct.unpack_from('<I',garage,gp+4*i)[0]-0x8c800000
        strings.append(garage[p:garage.index(0,p)].decode('ascii')if 0<=p<len(garage)else '')
    lines.append('static const char *const RECORD_TEXT[]={'+','.join(json.dumps(x)for x in strings)+'};')
    return '\n'.join(spec)+'\n','\n'.join(lines)+'\n'
if __name__=='__main__':
    spec,inc=extract()
    if '--check' in sys.argv:
        assert (ROOT/'decompile/record_book_spec.txt').read_text()==spec
        assert (ROOT/'psp/src/record_book.inc').read_text()==inc
    elif '--bake' in sys.argv:
        subprocess.run([sys.executable,'tools/jgc_convert.py','../psp/record_book.jgc',
            '--spec=record_book_spec.txt','--nolight=1','--source-material=1','--source-environment=1','--texmax=256'],cwd=ROOT/'decompile',check=True)
    else:
        (ROOT/'decompile/record_book_spec.txt').write_text(spec)
        (ROOT/'psp/src/record_book.inc').write_text(inc)
