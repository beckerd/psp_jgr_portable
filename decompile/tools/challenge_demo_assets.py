#!/usr/bin/env python3
"""Lossless original player challenge demonstrations, keyed by mission and set."""
import argparse,csv,hashlib,json,struct
from pathlib import Path
from title_route_assets import ROOT,bake
from garam_audio_assets import capture_cues
from mission_chain import chain_offsets, mission_source

CAPTURE=ROOT/'decompile/campaign_captures/challenge_routes_20260919'

def specs():
    rows=[]
    for mission,stage,chapter,sets in [
        ('S1M11',1,10,[(0,0,1,'gum'),(2,1,1,'gum'),(4,2,1,'gum'),
                       (6,3,2,'tab'),(8,4,2,'tab'),(20,5,2,'tab')]),
        ('S1M06',1,5,[(i*2,i,5,'piranha') for i in range(3)]),
        ('S1M07',1,6,[(0,0,1,'cube')]),
        ('S2M05',2,4,[(i*2,i,9,'garam') for i in range(3)]),
        ('S3M06',3,5,[(i*2,i,7,'mew') for i in range(3)]),
        ('S3M11',3,10,[(i*2,i,12,'noisetank') for i in range(3)]),
    ]:
        for record,subset,character,label in sets:
            path=f'{label}_demo{subset}.bin' if label in ('garam','mew') else f'challenge_{mission.lower()}_{subset}.bin'
            source=CAPTURE/f'dc_{mission.lower()}_{subset}'
            if label=='garam':source=ROOT/f'decompile/campaign_captures/kogane_ceiling_audio_20260917/dc_demo{subset}'
            if label=='mew':source=ROOT/f'decompile/campaign_captures/mew_routes_20260919/dc_demo{subset}'
            rows.append(dict(mission=mission,stage=stage,chapter=chapter,record=record,set=subset,
                             character=character,label=label,path=path,source=source))
    return rows

def write(path,data,check):
    if isinstance(data,str):data=data.encode()
    if check:assert path.read_bytes()==data,path
    else:path.write_bytes(data)

def spray_cues(raw):
    """Lossless run encoding of the completed source small-tag state.

    Gameplay GF callbacks still own paint/can/goal progress. Demo rendering
    must use the original overlay lifetime because live animation is bypassed.
    Emit another run whenever even one captured state/clock/target differs.
    """
    cues=[]
    for at in range(16,len(raw),4192):
        b=raw[at:at+0x900]
        u=lambda off:struct.unpack_from('<I',b,off)[0]
        f=lambda off:struct.unpack_from('<f',b,off)[0]
        tick=u(0x98);active=u(0x294);variant=int(u(0x560)==u(0x580))
        ref=u(0x2b8);frame=f(0x29c);target=[f(0x2a0+k*4) for k in range(3)]
        assert 0<tick<65536 and active in (0,1) and ref<65536
        assert not active or 160<=ref<=166
        cue=dict(tick=tick,ref=ref,active=active,variant=variant,frame=frame,target=target)
        previous=cues[-1] if cues else None
        if previous:
            same=all(cue[k]==previous[k] for k in ('ref','active','variant','target'))
            expected=previous['frame']+(tick-previous['tick'] if active else 0)
            if same and struct.pack('<f',frame)==struct.pack('<f',expected):continue
        cues.append(cue)
    return cues

def build(check=False):
    reports=[]
    lines=['/* Generated by challenge_demo_assets.py from completed original callbacks. */']
    for spec in specs():
        source=spec['source'];raw=(source/'title_actor_camera.bin').read_bytes()
        with (source/'title.csv').open() as f:rows=list(csv.DictReader(f))
        assert [int(r['player_clock']) for r in rows]==list(range(2,len(rows)+2))
        assert {struct.unpack_from('<I',raw,at+0x7c)[0] for at in range(16,len(raw),4192)}=={spec['character']}
        original=mission_source(next((ROOT/'decompile/afs/E_MISSIONDATA').glob('*'+spec['mission'].lower()+'.bin')))
        mission=original.read_bytes();offset=chain_offsets(mission)[spec['record']]
        assert struct.unpack_from('<I',mission,offset+0x14)[0]==6
        bank=struct.unpack_from('<I',mission,offset+0x10)[0]
        controller=ROOT/f'decompile/afs/MISSIONSET/{bank:03d}_mission_set_{bank:02d}.bin'
        ctrl=controller.read_bytes();base=0x8cde6000
        word=lambda address:struct.unpack_from('<I',ctrl,address-base)[0]
        header=base+chain_offsets(ctrl,b'JMSc')[spec['set']]
        stream=word(word(word(header+0x44)));ticks=0
        for at in range(stream-base+32,len(ctrl),4):
            if ctrl[at]&128:break
            ticks+=ctrl[at]+1
        assert ticks==len(rows)+2,(spec['mission'],spec['set'],ticks,len(rows))
        for at in range(16,len(raw),4192):
            frame=raw[at:at+4192];record=struct.unpack_from('<I',frame,0xc00)[0]-base
            assert frame[0xbfc:0xc00]==ctrl[record:record+4]
        log=(source/'flycast.log').read_text()
        assert f"selected record {spec['record']}" in log and f"REFERENCE complete samples={len(rows)}" in log
        assert 'Lua exception' not in log
        data,report=bake(source);assert report['character']==spec['character']
        target=ROOT/'psp'/spec['path'];write(target,data,check)
        events=capture_cues(source,target)
        assert all(0<=t<=len(rows)+1 and -1<=program<=127 for t,kind,program in events)
        symbol='CHALLENGE_'+spec['mission']+'_'+str(spec['set'])
        lines.append(f'static const RecruitAudioCue {symbol}[]={{')
        lines+=['    {%d,%d,%d},'%e for e in events];lines.append('};')
        sprays=spray_cues(raw)
        lines.append(f'static const RecruitSprayCue {symbol}_SPRAY[]={{')
        for s in sprays:
            floats=[float(v).hex()+'f' for v in [s['frame'],*s['target']]]
            lines.append('    {%d,%d,%d,%d,%s,{%s}},'%(s['tick'],s['ref'],s['active'],s['variant'],floats[0],','.join(floats[1:])))
        lines.append('};')
        reports.append(dict(spec,source=str(source.relative_to(ROOT)),**report,cues=events,spray_cues=sprays,
                            bank=bank,controller_source=str(controller.relative_to(ROOT)),
                            controller_sha256=hashlib.sha256(ctrl).hexdigest(),
                            mission_sha256=hashlib.sha256(mission).hexdigest(),
                            audio_sha256=hashlib.sha256((source/'audio.csv').read_bytes()).hexdigest()))
    lines.append('static const RecruitDemo RECRUIT_DEMOS[]={')
    for r in reports:
        symbol='CHALLENGE_'+r['mission']+'_'+str(r['set'])
        lines.append('    {"%s","%s","%s",%d,%d,%s,%d,%s_SPRAY,%d},'%
                     (r['mission'],r['path'],r['label'],r['set'],r['character'],symbol,len(r['cues']),symbol,len(r['spray_cues'])))
    lines+=['};','']
    write(ROOT/'psp/src/challenge_demo_data.inc','\n'.join(lines),check)
    write(ROOT/'psp/challenge_demos.json',json.dumps(reports,indent=2)+'\n',check)
    print('Original player challenges:',len(reports),'demonstrations;',sum(r['frames'] for r in reports),'samples')
    return reports

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true')
    build(ap.parse_args().check)
