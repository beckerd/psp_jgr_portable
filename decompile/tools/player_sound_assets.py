#!/usr/bin/env python3
"""Original 03ed98 foot-contact bytes and 05cf14 surface program mapping."""
from pathlib import Path
import struct
import sys
ROOT=Path(__file__).resolve().parents[2]
def generate():
    exe=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    feet=exe[0x17e890-0x10000:0x17e91c-0x10000]
    assert len(feet)==140 and set(feet)=={0,1}
    surfaces=struct.unpack_from('<64i',exe,0x1948f0-0x10000)
    assert all(-1<=v<19 for v in surfaces)
    lines=['/* Generated by player_sound_assets.py; unmodified executable tables. */',
           'static const unsigned char PLAYER_FOOT_CONTACT[5][28] = {']
    lines+=['    {'+','.join(map(str,feet[i:i+28]))+'},' for i in range(0,140,28)]
    lines+=['};','static const signed char PLAYER_SURFACE_SOUND[64] = {',
            '    '+','.join(map(str,surfaces)),'};','']
    return '\n'.join(lines)
if __name__=='__main__':
    result=generate()
    if '--check' in sys.argv:
        assert (ROOT/'psp/src/player_sound_tables.inc').read_text()==result
        print('Original foot-contact and surface-sound tables verified')
    else:print(result,end='')
