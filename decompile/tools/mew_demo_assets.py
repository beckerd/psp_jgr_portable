#!/usr/bin/env python3
"""Package completed original S3M06 movement, poses, camera, effects and audio."""
import argparse
import csv
import hashlib
import json
import struct
from title_route_assets import ROOT, bake
from garam_audio_assets import capture_cues

CAPTURE=ROOT/'decompile/campaign_captures/mew_routes_20260919'

def cues(index):
    return capture_cues(CAPTURE/f'dc_demo{index}',ROOT/f'psp/mew_demo{index}.bin')

def build(check=False):
    reports=[];audio=[]
    lines=['/* Generated by mew_demo_assets.py. Original S3M06 completed',
           '   sound initializers and actor +874/+878 loop retirement. */']
    for index in range(3):
        source=CAPTURE/f'dc_demo{index}'
        raw=(source/'title_actor_camera.bin').read_bytes()
        with (source/'title.csv').open() as f:rows=list(csv.DictReader(f))
        # 018fb0 binds the original CTRL character at actor +7c. Verify
        # the captured object itself, not just its CSV label or filename.
        assert {struct.unpack_from('<I',raw,at+0x7c)[0] for at in range(16,len(raw),4192)}=={7}
        assert [int(r['player_clock']) for r in rows]==list(range(2,len(rows)+2))
        log=(source/'flycast.log').read_text()
        assert f'MEW selected record {index*2}' in log and 'Lua exception' not in log
        assert f'MEW_REFERENCE complete samples={len(rows)}' in log
        data,report=bake(source)
        assert report['character']==7 and report['model']==0
        target=ROOT/f'psp/mew_demo{index}.bin'
        if check:assert target.read_bytes()==data
        else:target.write_bytes(data)
        reports.append(dict(report,set=index,record=index*2,source=str(source.relative_to(ROOT))))
        events=cues(index)
        assert all(0<=tick<=len(rows)+1 and 1<=kind<=4 and -1<=program<=127 for tick,kind,program in events)
        lines.append(f'static const RecruitAudioCue MEW_AUDIO_{index}[]={{')
        lines+=['    {%d,%d,%d},'%r for r in events];lines.append('};')
        audio.append(dict(set=index,cues=events,source=str(source.relative_to(ROOT)),
            audio_sha256=hashlib.sha256((source/'audio.csv').read_bytes()).hexdigest(),
            actor_sha256=report['source_sha256']))
    lines+=['static const RecruitAudioCue *const MEW_AUDIO[3]={MEW_AUDIO_0,MEW_AUDIO_1,MEW_AUDIO_2};',
            'static const unsigned MEW_AUDIO_COUNT[3]={'+','.join(str(len(r['cues'])) for r in audio)+'};','']
    for name,text in [('psp/mew_demos.json',json.dumps(reports,indent=2)+'\n'),
                      ('psp/mew_audio.json',json.dumps(audio,indent=2)+'\n'),
                      ('psp/src/mew_audio_data.inc','\n'.join(lines))]:
        target=ROOT/name
        if check:assert target.read_text()==text
        else:target.write_text(text)
    print('Original Mew demonstrations:',[r['frames'] for r in reports],
          'frames;', [len(r['cues']) for r in audio], 'sound cues')

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check',action='store_true');build(ap.parse_args().check)
