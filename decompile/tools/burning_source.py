#!/usr/bin/env python3
"""Fire/Kairiki bindings from the original US executable and ENEMY banks."""
from pathlib import Path
import struct, sys
from cutscene_sources import executable, afs_file
from enemy_motion_map import motion_headers
ROOT = Path(__file__).resolve().parents[2]

def header():
    e = executable()
    fmt = lambda xs: ','.join(str(x) if isinstance(x, int) else x.hex()+'f' for x in xs)
    lines = ['/* Generated by burning_source.py; original 07d854 / 08cff8. */']
    for name, addr in [('PAR_T6',0x8c1b9b2c),('PAR_T9',0x8c1b887c),('PAR_T25',0x8c1b88e4)]:
        p = [struct.unpack('<I' if i<3 or i>=20 else '<f',e.read(addr+i*4,4))[0] for i in range(24)]
        lines.append('static const float '+name+'[24]={'+fmt(p)+'};')
    states = [11,23,8,20,12,13,14,15,9,0,18,19,5,16,17,4,21,21,19,16]
    for name, bank, bones, table in [('FIRE',17,12,0x8c1b5fdc),('KAIRIKI',11,16,0x8c1b5df8)]:
        raw = afs_file('ENEMY',bank).read_bytes()
        motions = motion_headers(raw,bones,0x8ca00000)
        def clip(s):
            a=e.u(table+s*4)
            return motions.index(a-0x8ca00000) if a!=0xffffffff else -1
        st = states+[25,26,27,3] if name=='FIRE' else states+[25,26]
        mapped = [clip(s) for s in st]
        if mapped[0]<0: mapped[0]=clip(9) # 076764's absent-idle fallback
        lines += ['static const signed char '+name+'_MOTION['+str(len(st))+']={'+fmt(mapped)+'};',
                  'static const int '+name+'_GAIT_MOTION='+str(clip(7))+';',
                  'static const unsigned char '+name+'_FRAMES['+str(len(motions))+']={'+fmt([struct.unpack_from('<H',raw,a+2)[0] for a in motions])+'};']
        if name=='FIRE':
            lines.append('static const int FIRE_FRONT_GRAB_MOTION='+str(clip(22))+';')
            lines.append('static const int FIRE_AIM_MOTION[4]={'+fmt([clip(s) for s in (28,31,29,30)])+'};')
    for name, addr, count in [('FIRE_ANCHORS',0x8c1b8964,2),('KAIRIKI_ANCHORS',0x8c1b9c04,3)]:
        rows=[]
        i=0
        while len(rows)<count:
            d=e.u(addr+12*i)
            for j in range(d>>16):
                rows.append('{'+str(d&65535)+',{'+fmt(struct.unpack('<3f',e.read(e.u(addr+12*i+4)+12*j,12)))+'}}')
            i+=1
        assert len(rows)==count
        lines.append('static const struct {int bone;float pos[3];} '+name+'['+str(count)+']={'+','.join(rows)+'};')
    rows=[]
    for i in range(4):
        p=struct.unpack('<3fI',e.read(0x8c1b8980+16*i,16));rows.append('{'+fmt(p)+'}')
    lines.append('static const float FIRE_IDLE_TARGETS[4][4]={'+','.join(rows)+'};')
    lines.append('static const float KAIRIKI_RADIUS='+struct.unpack('<f',e.read(0x8c1b9b98,4))[0].hex()+'f;')
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    p=ROOT/'psp/src/burning_source.inc'
    if '--check' in sys.argv: assert p.read_text()==header()
    else: p.write_text(header())
