#!/usr/bin/env python3
"""Stable source fingerprint for crash reports; SHA-256 package receipts
remain the authority for exact installed binaries. No dirty git changes
are hidden behind a commit hash. Only rewrites the include when changed."""
import hashlib
from pathlib import Path
import sys
import subprocess

root = Path(__file__).resolve().parents[2]
paths = [root / 'psp/Makefile', Path(__file__)]
for folder in ('psp/src', 'psp/tools/meprx', 'psp/tools/crashprx'):
    paths += [p for p in (root / folder).rglob('*')
              if p.suffix in ('.c', '.h', '.inc', '.S') or p.name == 'Makefile']
out = root / 'psp/src/crash_build.inc'
h = hashlib.sha256()
for p in sorted(set(paths) - {out}):
    h.update(p.relative_to(root).as_posix().encode() + b'\0')
    h.update(p.read_bytes() + b'\0')
h.update(' '.join(sys.argv[1:]).encode())
h.update(subprocess.check_output(['psp-gcc', '--version']))
text = '/* Generated by crash_build_id.py. */\n#define JGR_CRASH_SOURCE_ID "' + h.hexdigest() + '"\n'
if not out.exists() or out.read_text() != text:
    out.write_text(text)
