def generate(exe):
    lines = ['/* Generated by decompile/tools/player_tuning.py; source table 0x8c182884. */',
             'const CharTuning PLAYER_TUNING[16] = {']
    for char in range(16):
        addr, = struct.unpack_from('<I', exe, 0x8c182884 + char * 4 - 0x8c010000)
        for block in (0x140,0x184,0x1c8,0x20c,0x250):
            for probe in range(3):
                assert struct.unpack_from('<f',exe,addr+block+probe*12-0x8c010000)[0]==0
                assert struct.unpack_from('<f',exe,addr+block+probe*12+8-0x8c010000)[0]==0
        assert exe[addr+0x140-0x8c010000:addr+0x164-0x8c010000]==exe[addr+0x184-0x8c010000:addr+0x1a8-0x8c010000]
        lines.append(f'    {{ /* character {char}, 0x{addr:08x} */')
        for name, offset, kind in FIELDS:
            value, = struct.unpack_from('<'+kind, exe, addr + offset - 0x8c010000)
            literal = value.hex()+'f' if kind == 'f' else str(value)
            lines.append(f'        .{name} = {literal}, /* +0x{offset:03x} */')
        lines.append('    },')
    return '\n'.join(lines + ['};', ''])

if __name__ == '__main__':
    root = Path(__file__).resolve().parents[2]
    result = generate((root/'decompile/extracted/1ST_READ.BIN').read_bytes())
    if '--check' in sys.argv:
        assert (root/'psp/src/player_tuning.inc').read_text() == result, 'regenerate player_tuning.inc'
        print('16 character movement records match the Dreamcast executable')
    elif '--write' in sys.argv:
        (root/'psp/src/player_tuning.inc').write_text(result)
    else:
        print(result, end='')
