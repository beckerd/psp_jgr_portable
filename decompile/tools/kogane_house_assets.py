#!/usr/bin/env python3
"""Kogane doors, gates, breakable walls/windows and hanging panels (03861c).

Exports the near/far CNK trees, original motions, every authored placement,
and the type-4 body boxes. These are event contacts, not solid world meshes.
"""
# These owners use the original normal draw path 234fc6 / mode 1,
# which submits both face directions (unlike the PLAY cel-hull path).

import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
import tempfile
from stage_render_assets import Source, tree, IDENTITY, EB, SB
import ninjalib as nl

ROOT=Path(__file__).resolve().parents[2]
DEC=ROOT/'decompile'
TYPES=(4,5,17,18,58,76,85,86,87)
MOTIONS={4:0x8c107d00,5:0x8c107cfc,17:0x8c107d10,18:0x8c107d20,58:0x8c107d24,76:0x8c107d1c,85:0x8c107d14,86:0x8c107d18,87:0x8c107d10}
SOUNDS={4:0,5:35,17:37,18:35,58:39,76:39,85:39,86:39,87:39}

def generate(directory):
    s=Source(2);tm=json.loads((DEC/'stage2_texmap.json').read_text())
    types=[];rows=[];boxes=[];bindings=[]
    with tempfile.TemporaryDirectory(prefix='jgr-house-textures-') as tmp:
        textures=Path(tmp)/'textures.bin'
        textures.write_bytes(b''.join((DEC/p).read_bytes() for p in tm['packs']))
        for index,ty in enumerate(TYPES):
            near=s.words(0x8c109d2c+4*ty)[0];far=s.words(0x8c10a004+4*ty)[0]
            motion=s.words(MOTIONS[ty])[0]
            frames=s.words(motion)[0]>>16
            first=len(boxes)
            def collision(node,parent):
                while node:
                    kind,flags,mesh=struct.unpack_from('<HHI',s.image,node-EB)
                    assert kind==4 and flags==25
                    pos=struct.unpack_from('<3f',s.image,node+12-EB)
                    ang=struct.unpack_from('<3i',s.image,node+24-EB)
                    scale=struct.unpack_from('<3f',s.image,node+36-EB)
                    m=nl.mmul(parent,nl.mmul(nl.placement_matrix(pos,ang),nl.mscale(*scale)))
                    verts=[nl.xform(m,struct.unpack_from('<3f',s.image,mesh+12*i-EB)) for i in range(8)]
                    center=nl.xform(m,struct.unpack_from('<3f',s.image,node+48-EB))
                    boxes.append(dict(node=f'{node:08x}',vertices=verts,center=center))
                    child,node=s.words(node+60,2)
                    if child:collision(child,m)
            collision(s.words(0x8c10a2dc+4*ty)[0],IDENTITY)
            for lod,root in enumerate((near,far)):
                texlist=s.words((0x8c109e98 if lod==0 else 0x8c10a170)+4*ty)[0]
                mapping=tm['texlists'].get(str(texlist))
                if str(root-SB) in tm['texmap']:assert mapping==tm['texmap'][str(root-SB)]
                if mapping is None:
                    assert all(not node['model'] for node,_ in tree(s,root,IDENTITY))
                    mapping=[0]  # original empty far hierarchy, no textured mesh
                bindings.append(dict(type=ty,lod=lod,texlist=f'{texlist:08x}',source_indices=mapping if texlist else []))
                rows.append(f'house{ty}_{lod}:afs/STAGE2/000_st2dat.bin:{textures}:0,0,0,0:rawat:{SB:x}:{root:x}:{motion:x}:texmap='+','.join(map(str,mapping))+':lighting=1:cull=none')
            types.append(dict(type=ty,near=f'{near:08x}',far=f'{far:08x}',motion=f'{motion:08x}',frames=frames,
                              first_box=first,boxes=len(boxes)-first,sound=SOUNDS[ty]))
        subprocess.run([sys.executable,'tools/jgc_convert.py',str(directory/'kogane_house.jgc'),
                        '--motions=1','--texmax=512','--source-material=1','--source-environment=1',*rows],cwd=DEC,check=True)
    placements=[r for r in s.records(0x8c108284,114,40,91) if r['pid'] in TYPES]
    assert len(placements)==39 and len({p['address'] for p in placements})==39
    # The old city render bank contains none of these near or far models.
    side=json.loads((ROOT/'psp/stage2.jgs.map.json').read_text())
    assert not {v[0] for v in side}&{int(t[k],16)-SB for t in types for k in ('near','far')}
    def f(v):return float(v).hex()+'f'
    def vector(v):return '{'+','.join(f(x) for x in v)+'}'
    lod_distance2=struct.unpack_from('<f',s.exe,0x8c039140-EB)[0]
    lines=['/* Generated by kogane_house_assets.py from the original US game. */',
           'static const float house_lod_distance2='+f(lod_distance2)+';',
           'static const HouseType house_types[]={']
    for t in types:lines.append('    {%du,%du,%du,%du,%du},'%(t['type'],t['frames'],t['first_box'],t['boxes'],t['sound']))
    lines+=['};','static const HouseBox house_boxes[]={']
    for b in boxes:lines.append('    {'+vector([x for v in b['vertices'] for x in v])+','+vector(b['center'])+'},')
    lines+=['};','static const HousePlacement house_placements[]={']
    for p in placements:
        lines.append('    {0x%08xu,%du,%du,%s,{%s}},'%(p['address'],TYPES.index(p['pid']),p['sector'],vector(p['pos']),','.join(map(str,p['ang']))))
    lights=[struct.unpack_from('<8f',s.exe,0x8c17c580+sector*32-EB) for sector in range(114)]
    lines+=['};','static const float house_lights[114][8]={']
    lines += ['    '+vector(light)+',' for light in lights]
    lines+=['};','']
    (directory/'kogane_house_data.inc').write_text('\n'.join(lines))
    meta=dict(types=types,boxes=boxes,placements=placements,light_table="8c17c580",lights=lights,texture_bindings=bindings,lod_distance2=lod_distance2,
              motion_tables={str(k):f'{v:08x}' for k,v in MOTIONS.items()},
              source_sha256=hashlib.sha256(s.data).hexdigest(),
              model_sha256=hashlib.sha256((directory/'kogane_house.jgc').read_bytes()).hexdigest())
    (directory/'kogane_house_assets.json').write_text(json.dumps(meta,indent=2)+'\n')

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    with tempfile.TemporaryDirectory(prefix='jgr-house-export-') as tmp:
        directory=Path(tmp);generate(directory)
        for name in ('kogane_house.jgc','kogane_house_assets.json','kogane_house_data.inc'):
            target=ROOT/'psp'/('src' if name.endswith('.inc') else '')/name
            if args.check:assert target.read_bytes()==(directory/name).read_bytes(),name
            else:target.write_bytes((directory/name).read_bytes())
if __name__=='__main__':main()
