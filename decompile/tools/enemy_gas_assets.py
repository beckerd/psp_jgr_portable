#!/usr/bin/env python3
"""07a2d0 riot gas: source flash/cloud meshes, motions and collision trees.
ENEMY003 bindings 1b5c34..60. Keep both random variants and stage-2 colors.
Collision nodes retain their own bind defaults and DFS motion channel order.
"""
import sys, subprocess, json, struct, tempfile
from pathlib import Path
from cutscene_sources import executable, afs_file, fingerprint
ROOT = Path(__file__).resolve().parents[2]
BASE = 0x8ca00000

def export():
    e = executable(); dp = afs_file('ENEMY', 3); tp = afs_file('ENEMY', 2)
    data = bytearray(dp.read_bytes()); u = lambda a: struct.unpack_from('<I', data, a-BASE)[0]
    models = []; bodies = []; collision_roots = []
    for variant in range(2):
        nodes = []
        def walk(addr, parent=-1):
            while addr:
                kind, shape = struct.unpack_from('<2I', data, addr-BASE)
                assert kind & 65535 in (0, 2)
                sphere = struct.unpack_from('<4f', data, shape-BASE) if shape else (0.,)*4
                assert not shape or kind >> 16 == 26
                assert data[addr-BASE+48:addr-BASE+60] == bytes(12)
                own = len(nodes); nodes.append((addr, parent, sphere))
                walk(u(addr+60), own); addr = u(addr+64)
        walk(e.u(0x8c1b5c60+variant*4)); assert len(nodes) == 6
        # The model converter understands 52-byte Ninja render nodes. These
        # meshless nodes are a lossless view of the 68-byte collision tree.
        ptrs = {a: BASE+len(data)+i*52 for i,(a,_,_) in enumerate(nodes)}
        collision_roots.append(ptrs[nodes[0][0]])
        for a, parent, sphere in nodes:
            at = a-BASE
            data += struct.pack('<2I', 0, 0) + data[at+12:at+48] + struct.pack('<2I', ptrs.get(u(a+60),0),ptrs.get(u(a+64),0))
        bodies.append([dict(parent=p, sphere=s) for _,p,s in nodes])
    with tempfile.TemporaryDirectory(prefix='jgr-gas-') as tmp:
        source = Path(tmp)/'kidoutai.bin'; source.write_bytes(data)
        args = [sys.executable, 'tools/jgc_convert.py', str(ROOT/'psp/enemygas.jgc'),
                '--nolight=1', '--source-material=1', '--source-environment=1']
        for stage2 in range(2):
            for variant in range(2):
                for part in range(2):
                    root = e.u(0x8c1b5c34+stage2*16+variant*4+part*8)
                    motion = e.u(0x8c1b5c54+part*4)
                    models.append(dict(root=root,motion=motion,frames=u(motion)>>16))
                    # 07a588 sets control 0xc00/0xc20 and ORs 0x800 into
                    # every strip: alpha rendering even before the fade.
                    # All source gas materials use SRC_ALPHA/INV_SRC_ALPHA.
                    args.append(f'gas{stage2}{variant}{part}:{source}:{tp}:0,0,0,0:rawat:{BASE:x}:{root:x}:{motion:x}:alpha=1')
        for variant, root in enumerate(collision_roots):
            args.append(f'gasbody{variant}:{source}:{tp}:0,0,0,0:rawat:{BASE:x}:{root:x}:{e.u(0x8c1b5c58):x}')
        subprocess.run(args,cwd=ROOT/'decompile',check=True)
    lines=['/* Generated by enemy_gas_assets.py; 1b5c60, attribute 26. */',
           'static const float GAS_SPHERES[2][6][4]={']
    for body in bodies:
        lines.append('    {' + ','.join('{'+','.join(v.hex()+'f' for v in n['sphere'])+'}' for n in body) + '},')
    (ROOT/'psp/src/enemy_gas_body.inc').write_text('\n'.join(lines+['};','']))
    (ROOT/'psp/enemygas.json').write_text(json.dumps(dict(data=fingerprint(dp),models=models,bodies=bodies),indent=2)+'\n')
if __name__=='__main__': export()
