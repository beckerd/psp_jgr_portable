#!/usr/bin/env python3
"""Bake observed original Garam sound initializers and persistent-owner stops."""
import argparse,csv,hashlib,json,struct
from title_route_assets import ROOT,bake
CAPTURE=ROOT/'decompile/campaign_captures/kogane_ceiling_audio_20260917'

def capture_cues(folder,route):
    # Instrumentation must not change even one displayed world/pose/camera byte.
    assert bake(folder)[0]==route.read_bytes()
    data=(folder/'title_actor_camera.bin').read_bytes();events=[]
    with (folder/'audio.csv').open() as stream:rows=list(csv.DictReader(stream))
    parents={int(r['parent']) for r in rows};assert len(parents)==1
    for order,r in enumerate(rows):
        tick,kind,bank,program=[int(r[k]) for k in ('tick','kind','bank','program')]
        assert bank==(7 if kind==1 else 4) and kind in (1,2,3,4)
        events.append((tick,order,kind,program))
    owners=[0,0];active=[False,False]
    for at in range(16,len(data),4192):
        p=data[at:at+0x900];tick=struct.unpack_from('<I',p,0x98)[0]
        for k,off in enumerate((0x874,0x878)):
            owner=struct.unpack_from('<I',p,off)[0]
            if owners[k] and not owner:events.append((tick,10000+k,3+k,-1))
            owners[k]=owner
    events.sort()
    for tick,order,kind,program in events:
        if kind in (3,4):
            assert active[kind-3]==(program<0),(folder,tick,kind,program)
            active[kind-3]=program>=0
    assert not any(active),'demo must retire its loop owners'
    return [(tick,kind,program) for tick,_,kind,program in events]

def cues(index):
    return capture_cues(CAPTURE/f'dc_demo{index}',ROOT/f'psp/garam_demo{index}.bin')

def build(check=False):
    lines=['/* Generated by garam_audio_assets.py. Original 05d288/2c0/2f8/330',
           '   initializers; loop termination from completed actor +874/+878. */']
    report=[]
    for index in range(3):
        events=cues(index);lines.append(f'static const RecruitAudioCue GARAM_AUDIO_{index}[]={{')
        lines+=['    {%d,%d,%d},'%r for r in events];lines.append('};')
        folder=CAPTURE/f'dc_demo{index}'
        report.append(dict(set=index,cues=events,source=str(folder.relative_to(ROOT)),
            audio_sha256=hashlib.sha256((folder/'audio.csv').read_bytes()).hexdigest(),
            actor_sha256=hashlib.sha256((folder/'title_actor_camera.bin').read_bytes()).hexdigest()))
    lines+=['static const RecruitAudioCue *const GARAM_AUDIO[3]={GARAM_AUDIO_0,GARAM_AUDIO_1,GARAM_AUDIO_2};',
            'static const unsigned GARAM_AUDIO_COUNT[3]={'+','.join(str(len(r['cues'])) for r in report)+'};','']
    for name,text in [('psp/src/garam_audio_data.inc','\n'.join(lines)),('psp/garam_audio.json',json.dumps(report,indent=2)+'\n')]:
        target=ROOT/name
        if check:assert target.read_text()==text
        else:target.write_text(text)
    print('Original Garam audio:',[len(r['cues']) for r in report],'cues; all three rendered routes unchanged')
if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');build(ap.parse_args().check)
