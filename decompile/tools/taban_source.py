#!/usr/bin/env python3
"""Original Taban tuning (21b524) and private animation bank (1b65cc)."""
from pathlib import Path
import struct,sys
from enemy_motion_map import motion_headers
ROOT=Path(__file__).resolve().parents[2]
def header():
    exe=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    bank=(ROOT/'decompile/afs/ENEMY/035_tabandat.bin').read_bytes()
    pointers=struct.unpack_from('<31I',exe,0x1b65cc-0x10000)
    addresses=motion_headers(bank,12,0x8ca00000)
    slots=[addresses.index(p-0x8ca00000) for p in pointers]
    frames=[struct.unpack_from('<H',bank,p+2)[0] for p in addresses]
    params=[struct.unpack_from('<I' if i<3 or i>=20 else '<f',exe,0x21b524-0x10000+4*i)[0] for i in range(24)]
    states=[15,30,30,29,0,15,15,6,7,8,1,2] # 21b430 animation handlers
    fmt=lambda xs:','.join(str(v) if isinstance(v,int) else v.hex()+'f' for v in xs)
    anchor=struct.unpack_from('<6f',exe,0x21b584-0x10000)
    assert struct.unpack_from('<I',exe,0x21b59c-0x10000)[0]==0x20009
    assert struct.unpack_from('<I',exe,0x21b4e0-0x10000)[0]==0x1b0002
    assert struct.unpack_from('<4f',exe,0x21b4d0-0x10000)==(0,0,0,3)
    return ('/* Generated by taban_source.py from original 21b524 / 1b65cc. */\n'
      +'static const float PAR_TABAN[24]={'+fmt(params)+'};\n'
      +'static const signed char TABAN_MOTION[12]={'+fmt([slots[s] for s in states])+'};\n'
      +'static const unsigned char TABAN_FRAMES[31]={'+fmt(frames)+'};\n'
      +'enum { TABAN_GAIT_MOTION='+str(slots[13])+' };\n')
def attack_header():
    exe=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    anchor=struct.unpack_from('<6f',exe,0x21b584-0x10000)
    return ('/* Original attachment 21b59c and sphere 21b4e0. */\n'
        +'enum { TABAN_ANCHOR_BONE=9, TABAN_HIT_ATTRIBUTE=27 };\n'
        +'static const float TABAN_ANCHORS[2][3]={{'+','.join(v.hex()+'f' for v in anchor[:3])+'},{'+','.join(v.hex()+'f' for v in anchor[3:])+'}};\n')
def texture():
    from pvr_decode import decode
    raw=(ROOT/'decompile/afs/ENEMY/034_tabantxr.bin').read_bytes()
    # Original 0fb6ec binds texlist 21b3d0 slot 1, the second PVR.
    start=raw.index(b'PVRT',23936);length=struct.unpack_from('<I',raw,start+4)[0]
    im=decode(raw[start:start+8+length]).convert('RGBA');w,h=im.size
    return struct.pack('<4sIHH',b'TEX1',1,w,h)+b''.join(struct.pack('<H',(a>>4)<<12|(b>>4)<<8|(g>>4)<<4|(r>>4)) for r,g,b,a in im.getdata())
if __name__=='__main__':
    for p,data in [(ROOT/'psp/src/taban_source.inc',header().encode()),(ROOT/'psp/src/taban_attack_source.inc',attack_header().encode()),(ROOT/'psp/tabanfx.bin',texture())]:
        if '--check' in sys.argv:assert p.read_bytes()==data,p
        else:p.write_bytes(data)
