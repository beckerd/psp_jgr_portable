#!/usr/bin/env python3
"""Cutscene dialog from afs/EVENT/*_event_NNNN.bin (event scripts, loaded at 0x8c900000): the text block holds the subtitle for each
language as a printable string with control codes ($w wait, $m line break, $c[n] colour). The first block is English. Message ids
(FUN_8c04eab8 / FUN_8c04ece4 event codes 0xe/0x1c) map to names through the descriptor table 0x8c1d0fd0 + id*0x44 (+8 = "EVENT_NNNN").
Writes psp/events.txt ("NAME<TAB>text") and psp/src/eventnames.h (id -> name)."""
import re, glob, os, struct
e=open("extracted/1ST_READ.BIN","rb").read(); EB=0x8c010000
names=[e[0x8c1d0fd0+i*0x44+8-EB:0x8c1d0fd0+i*0x44+32-EB].split(b"\0")[0].decode("ascii","replace") for i in range(0x70)]
texts={}
for fp in sorted(glob.glob("afs/EVENT/*_event_*.bin")):
    if "txr" in fp: continue
    d=open(fp,"rb").read(); name="EVENT_"+os.path.basename(fp).split("_")[-1][:4]
    strs=[m.group(0).decode("latin-1") for m in re.finditer(rb"[ -~]{8,}",d)]
    en=[s for s in strs if "$" in s and re.search(r"[A-Za-z]{3,}",s)]
    if not en: continue
    t=en[0]
    t=re.sub(r"\$c\[\d+\]","",t); t=t.replace("$w","").replace("$f","\n\n").replace("$n","\n").replace("$m","\n"); t=re.sub(r"[ ]{2,}"," ",t).strip()
    if t: texts[name]=t
with open("../psp/events.txt","w") as out:
    for k,v in sorted(texts.items()): out.write(k+"\t"+v.replace("\n","\\n")+"\n")
with open("../psp/src/eventnames.h","w") as out:
    out.write("/* generated by tools/jgs_events.py: cutscene descriptor names 0x8c1d0fd0 (id -> EVENT_NNNN) */\nstatic const char *EVENT_NAMES[112] = {"+",".join('"%s"'%n for n in names)+"};\n")
print(len(texts),"event texts;", list(texts.items())[:3])
