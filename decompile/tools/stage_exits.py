#!/usr/bin/env python3
"""Extract Benten's stage-owned exit quads, registered by 8c031aa8.

8c031e00 points to the 40-entry table at 8c177c08. Callback 8c032118
uses entries 0x0e..0x20 to request phase 0x0b; these are separate from
the JMDc mission event lists. Bounds are baked using 0c2d78's float32
arithmetic, which the host test also checks against mission_quad_prepare.
"""
from pathlib import Path
import argparse
import struct

ROOT = Path(__file__).resolve().parents[2]
BASE = 0x8c010000
TABLE = 0x8c177c08


def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]


def records():
    data = (ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    word = lambda address: struct.unpack_from('<I', data, address-BASE)[0]
    assert word(0x8c031e00) == TABLE
    assert word(TABLE+40*4) == 0
    result = []
    for index in range(0x0e, 0x21):
        address = word(TABLE+index*4)
        flags, *values = struct.unpack_from('<I19f', data, address-BASE)
        assert flags == 6, 'An area-specific quad requires an area input'
        assert values[15:] == [0.]*4
        vertices = [values[j:j+3] for j in range(0, 12, 3)]
        center = [f32(f32(f32(f32(vertices[0][j]+vertices[1][j])+
                                vertices[2][j])+vertices[3][j])/4.)
                  for j in range(3)]
        radii = []
        for vertex in vertices:
            d = [f32(v-c) for v, c in zip(vertex, center)]
            squares = [f32(v*v) for v in d]
            radii.append(f32(f32(squares[0]+squares[1])+squares[2]))
        radius = f32(max(radii)*f32(1.2))
        # 032118: 0e..15 unconditional; 16..1e only mission ID 10;
        # 1f..20 only ID 11. These are IDs (+0c), not mission kinds.
        mission = -1 if index <= 0x15 else 10 if index <= 0x1e else 11
        direction = 0x10000 if index in (0x16, 0x1b, 0x1c, 0x1f) else 0x20000
        result.append((index, address, flags, vertices, values[12:15], center,
                       radius, mission, direction))
    return result


def generate():
    vec = lambda values: '{'+','.join(x.hex()+'f' for x in values)+'}'
    lines = ['/* Generated by stage_exits.py from 1ST_READ.BIN; do not edit. */',
             'static const StageExitBoundary benten_exits[] = {']
    for index, address, flags, vertices, normal, center, radius, mission, direction in records():
        lines += [f'    {{ /* table[{index:#04x}] = {address:08x} */',
                  '        {'+str(flags)+',{'+','.join(vec(v) for v in vertices)+'},',
                  '         '+vec(normal)+','+vec(center)+','+radius.hex()+'f},',
                  f'        {mission},0x{direction:x}u,{index}', '    },']
    return '\n'.join(lines+['};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT/'psp/src/stage_exit_data.inc'
    text = generate()
    if args.check:
        assert path.read_text() == text, 'Stage exits differ from the original executable'
    else:
        path.write_text(text)
