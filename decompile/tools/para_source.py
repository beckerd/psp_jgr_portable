#!/usr/bin/env python3
"""Extract Para's original US parameters, state bindings and motion lengths."""
from pathlib import Path
import struct, sys

ROOT=Path(__file__).resolve().parents[2]

def header():
    exe=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    data=(ROOT/'decompile/afs/ENEMY/013_paradat.bin').read_bytes()
    pointers=struct.unpack_from('<35I',exe,0x1b5e8c-0x10000)
    addresses=sorted(set(p for p in pointers if 0x8ca00000<=p<0x8ca00000+len(data)))
    slots=[addresses.index(p) if p in addresses else -1 for p in pointers]
    frames=[struct.unpack_from('<H',data,p-0x8ca00000+2)[0] for p in addresses]
    states=[11,23,8,20,12,13,14,15,25,25,18,19,5,16,17,4,21,21,19,16,25,26,27,28,29]
    clips=[slots[s] for s in states]
    params=[]
    for i in range(24):
        v=struct.unpack_from('<I' if i<3 or i>=20 else '<f',exe,0x1b823c-0x10000+i*4)[0]
        params.append(str(v) if isinstance(v,int) else v.hex()+'f')
    attack=struct.unpack_from('<9I',exe,0x1b829c-0x10000)
    return ('/* Generated by para_source.py; source 1b823c / 1b829c / 1b5e8c. */\n'
        +'static const float PAR_T7[24]={'+','.join(params)+'};\n'
        +'static const signed char PARA_MOTION[25]={'+','.join(map(str,clips))+'};\n'
        +'static const int PARA_GAIT_MOTION='+str(slots[7])+'; /* 0768e8: semantic slot 7 */\n'
        +'static const unsigned char PARA_FRAMES['+str(len(frames))+']={'+','.join(map(str,frames))+'};\n'
        +'static const unsigned PARA_ATTACK[9]={'+','.join(hex(v) for v in attack)+'};\n')

if __name__=='__main__':
    target=ROOT/'psp/src/para_source.inc'
    if '--check' in sys.argv:assert target.read_text()==header()
    else:target.write_text(header())
