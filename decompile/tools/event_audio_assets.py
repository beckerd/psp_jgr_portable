#!/usr/bin/env python3
"""Resolve EVENT sound commands through original 096294/0e7860 loader tables."""
import argparse,struct
from event_assets import catalog
from cutscene_sources import ROOT,executable,afs_file

PROFILE={27:0x1d43b4,28:0x1d4a98,29:0x1d4504,30:0x1d42b8,31:0x1d45ac,
32:0x1d3f38,33:0x1d4c58,34:0x1d4cac,35:0x1d4e6c,36:0x1d502c,
37:0x1d4cac,38:0x1d4e6c,39:0x1d502c,40:0x1d3cd0,41:0x1d3dcc,
42:0x1d4cac,43:0x1d4e6c,44:0x1d502c,45:0x1d3b2c,46:0x1d3e90,
47:0x1d40f8,48:0x1d468c,49:0x1d4aec,50:0x1d4b94,51:0x1d4718,
52:0x1d4328,53:0x1d48a0,54:0x1d49d4,55:0x1d476c}

def resolve(stage,kind,bank,ref):
    ex=executable();logical=bank
    if kind in (0x5b,0x5c,0x5d):kind=0x29
    if kind==0x36:
        logical,ref=struct.unpack('<iI',ex.read(0x8c1ce468+ref*8,8))
        kind=0x29 if logical<0 else 0x2a
    if kind==0x29:
        if ref>=0x80000000:logical=15;ref&=65535
        else:
            typ=ref>>16;ref&=65535
            source=ex.u(0x8c1ba590+typ*4)
            record=ex.u(ex.u(0x8c05bf94)+source*4)
            assert ex.u(record)==0x1d and ex.u(record+32)==0x52
            file=ex.u(record+4);address=0x8c000000+PROFILE[source]
            logical=11
    if logical in (4,15,16,17,18):
        address={4:0x8c1d3384,15:0x8c1d51ec,16:0x8c1d5400,17:0x8c1d595c,18:0x8c1d5b38}[logical]
        # Original stage audio load records, in PSP's one-based city order.
        world={1:(64,70,76),2:(63,68,74),3:(62,67,73),4:(43,69,75),5:(65,67,73),6:(65,67,73)}[stage]
        file={4:5,15:66,16:world[0],17:world[1],18:0}[logical]
    backend,cls,dist,far,near,unknown,suppressed=struct.unpack('<IIfffii',ex.read(address+ref*28,28))
    assert backend in (0,1,2) and cls<=18 and not suppressed,(stage,kind,bank,ref)
    patch=72 if logical==15 else world[2] if logical==17 else 0
    patchbank=1 if logical==15 else 2
    if backend!=2:
        data=afs_file('E_SND_SE',file).read_bytes()
        assert data[:4]==(b'SOSB' if backend==0 else b'SMSB')
        assert ref<struct.unpack_from('<I',data,12)[0]
    return file,ref,backend,cls,logical,patch,patchbank,dist,far,near

def rows():
    events=catalog();result={}
    for e in events:
        keys=set();owner=events[e['asset_descriptor']]
        for c in owner['audio_commands']:
            op=c['opcode'];a=c['arguments']
            if op not in (0x29,0x2a,0x35,0x36):continue
            key=(op,a[1],a[1] if op in (0x29,0x36) else a[2])
            keys.add(key)
        for op,ref in ((0x5b,0x1000d),(0x5c,0xffff0010),(0x5d,0x90005)):
            if op in owner['opcodes']:keys.add((op,ref,ref))
        if keys:result[e['id']]=[(key,resolve(e['stage']+1,*key)) for key in sorted(keys)]
    return result

def generated():
    lines=['/* Generated by event_audio_assets.py; source selectors and profiles. */']
    for id,values in rows().items():
        lines.append(f'static const EventAudioCue EVENT_AUDIO_{id}[]={{')
        for key,v in values:
            lines.append('    {%du,0x%xu,0x%xu,%s,{%d,%.9gf,%.9gf,%.9gf}},'%(*key,','.join(str(x) for x in v[:7]),v[2],*v[7:]))
        lines.append('};')
    lines+=['static inline const EventAudioCue *event_audio_cues(int id,unsigned *count)','{','    switch(id) {']
    for id,values in rows().items():lines.append(f'    case {id}:*count={len(values)};return EVENT_AUDIO_{id};')
    lines+=['    default:*count=0;return NULL;','    }','}','']
    # C requires a decimal point for float literals such as 1000.f.
    import re
    return re.sub(r'(?<=[,{])(-?[0-9]+)f(?=[,}])',r'\1.f','\n'.join(lines))

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    data=generated();path=ROOT/'psp/src/event_audio_tables.inc'
    if args.check:assert path.read_text()==data
    else:path.write_text(data)
    print('Original EVENT voice selectors and spatial profiles verified')
if __name__=='__main__':main()
