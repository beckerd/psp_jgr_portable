#!/usr/bin/env python3
"""Package untouched final SMSB/SMPB; recover MANATEE pitch lookup tables.

AEG timing constants use the installed reference emulator's hardware model.
This does not claim measured PSP/Dreamcast envelope or DSP equivalence.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import struct
ROOT=Path(__file__).resolve().parents[2]
def tables(reference):
    driver=(ROOT/'decompile/extracted/JETRADIO/MANATEE.DRV').read_bytes()[32:]
    lines=['/* Generated by smsb_assets.py. Original MANATEE pitch tables;\n   envelope-rate constants from the local Flycast hardware model. */']
    def array(name,ctype,values):
        lines.append(f'static const {ctype} {name}[{len(values)}]={{')
        lines.extend('    '+','.join(str(v) for v in values[i:i+16])+',' for i in range(0,len(values),16));lines.append('};')
    array('SMSB_NOTE','unsigned char',driver[0x4210:0x42f4])
    array('SMSB_PITCH','unsigned char',driver[0x42f4:0x48f4])
    source=Path(reference).read_text()
    for kind in ('Attack','DSR'):
        raw=re.search(r'AEG_'+kind+r'_Time\[64\]\s*=\s*\{([^}]+)',source)[1]
        times=[struct.unpack('<f',struct.pack('<f',float(v)))[0] for v in raw.split(',') if v.strip()]
        values=[]
        for t in times:
            if t<0:v=0
            elif kind=='Attack':v=65536 if t==0 else math.floor(65536/(1-1/math.pow(640,1/(44.1*t)))+.5)
            else:v=67108863 if t==0 else math.floor(67108863/(44.1*t)+.5)
            values.append(v)
        assert len(values)==64
        array('SMSB_EG_'+kind.upper(),'uint32_t',values)
    return '\n'.join(lines)+'\n'
def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true')
    ap.add_argument('--reference-source',type=Path,required=True,help='Explicit Flycast sgc_if.cpp hardware model input')
    args=ap.parse_args()
    manifest={}
    for filename,source in [('finalseq.bin','069_s_last_seq.msb'),('finalpatch.bin','075_s_last_seq.mpb')]:
        src=ROOT/'decompile/afs/E_SND_SE'/source;data=src.read_bytes();target=ROOT/'psp'/filename
        if args.check:assert target.read_bytes()==data
        else:target.write_bytes(data)
        manifest[filename]=dict(source=str(src.relative_to(ROOT)),bytes=len(data),sha256=hashlib.sha256(data).hexdigest())
    target=ROOT/'psp/src/smsb_tables.inc';text=tables(args.reference_source)
    if args.check:assert target.read_text()==text
    else:target.write_text(text)
    print(json.dumps(manifest,indent=2))
if __name__=='__main__':main()
