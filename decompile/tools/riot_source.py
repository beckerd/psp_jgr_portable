#!/usr/bin/env python3
"""Kidoutai gas-squad constants from the US executable and original ENEMY bank."""
from pathlib import Path
import struct
import sys
from enemy_motion_map import motion_headers

ROOT = Path(__file__).resolve().parents[2]

def header():
    exe = (ROOT / 'decompile/extracted/1ST_READ.BIN').read_bytes()
    bank = (ROOT / 'decompile/afs/ENEMY/003_kidoutaidat.bin').read_bytes()
    pointers = struct.unpack_from('<36I', exe, 0x1b5ba0-0x10000)
    addresses = motion_headers(bank, 13, 0x8ca00000)
    slots = [addresses.index(p-0x8ca00000) if p-0x8ca00000 in addresses else -1 for p in pointers]
    slots[11] = slots[9]  # loader 07947c copies runtime[9] to [11]
    frames = [struct.unpack_from('<H', bank, p+2)[0] for p in addresses]
    params = []
    for i in range(24):
        v = struct.unpack_from('<I' if i < 3 or i >= 20 else '<f', exe, 0x1b76f4-0x10000+i*4)[0]
        params.append(str(v) if isinstance(v, int) else v.hex()+'f')
    states = [11,23,8,20,12,13,14,15,9,0,18,19,5,16,17,4,21,21,19,16,26,28,30]
    return ('/* Generated by riot_source.py: 1b76f4 / 1b7754 / 1b5ba0. */\n'
        +'static const float PAR_T4[24]={'+','.join(params)+'};\n'
        +'static const signed char RIOT_MOTION[23]={'+','.join(str(slots[s]) for s in states)+'};\n'
        +'static const int RIOT_GAIT_MOTION='+str(slots[7])+';\n'
        +'static const int RIOT_FRONT_GRAB_MOTION='+str(slots[22])+';\n'
        +'static const signed char RIOT_GAS_OVERLAY[3]={'+','.join(str(slots[s]) for s in (27,29,31))+'};\n'
        +'static const signed char RIOT_TURN_OVERLAY[2]={'+','.join(str(slots[s]) for s in (34,35))+'};\n'
        +'static const unsigned char RIOT_FRAMES['+str(len(frames))+']={'+','.join(map(str,frames))+'};\n'
        +'static const unsigned RIOT_ATTACK[2]={'+','.join(map(str,struct.unpack_from('<2I',exe,0x1b7754-0x10000)))+'};\n')

if __name__ == '__main__':
    target = ROOT / 'psp/src/riot_source.inc'
    if '--check' in sys.argv:
        assert target.read_text() == header()
    else:
        target.write_text(header())
