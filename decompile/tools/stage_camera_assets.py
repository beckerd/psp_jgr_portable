#!/usr/bin/env python3
"""Extract Shibuya's fixed passage camera registered by original 02fb6c."""
import argparse
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ADDRESS = 0x8c175a40

def region_bytes():
    data = (ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    assert struct.unpack_from('<II', data, 0x8c175b18-0x8c010000) == (ADDRESS, 1)
    return data[ADDRESS-0x8c010000:ADDRESS-0x8c010000+0xd8]

def generate():
    data = region_bytes()
    word = lambda off: struct.unpack_from('<i', data, off)[0]
    vec = lambda off: '{'+','.join(v.hex()+'f' for v in struct.unpack_from('<3f', data, off))+'}'
    return '\n'.join([
        '/* Generated by stage_camera_assets.py from 1ST_READ.BIN; do not edit. */',
        'static const StageCameraRegion shibuya_passage_camera = { /* 8c175a40 */',
        f'    {word(0)},',
        '    {'+','.join(vec(4+i*12) for i in range(6))+'},',
        '    {'+','.join(vec(0x4c+i*12) for i in range(6))+'},',
        f'    {vec(0x94)}, {vec(0xa0)}, {word(0xac)}, {word(0xb0)}, {word(0xb4)},',
        f'    {vec(0xb8)}, {word(0xc4)}, {vec(0xc8)}, {word(0xd4)}',
        '};', ''])

if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    path = ROOT/'psp/src/stage_camera.inc'
    if args.check: assert path.read_text() == generate()
    else: path.write_text(generate())
