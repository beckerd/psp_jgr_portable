#!/usr/bin/env python3
"""Original Bomb/SWAT 07b474 family: tuning, semantic clips and attacks."""
from pathlib import Path
import struct,sys
from enemy_motion_map import motion_headers
ROOT=Path(__file__).resolve().parents[2]
def header():
    exe=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    bank=(ROOT/'decompile/afs/ENEMY/009_bombdat.bin').read_bytes()
    u=lambda a:struct.unpack_from('<I',exe,a-0x8c010000)[0]
    addresses=motion_headers(bank,12,0x8ca00000)
    slots=[addresses.index(u(0x8c1b5d64+i*4)-0x8ca00000) for i in range(26)]
    states=[11,23,8,20,12,13,14,15,9,0,18,19,5,16,17,4,21,21,19,16]
    fmt=lambda xs:','.join(str(v) if isinstance(v,int) else v.hex()+'f' for v in xs)
    lines=['/* Generated by bomb_source.py from original 07b474 bindings. */']
    for label,base in [('A',0x8c1b7e0c),('B',0x8c1b7e80)]:
        params=[struct.unpack_from('<I' if i<3 or i>=20 else '<f',exe,base-0x8c010000+4*i)[0] for i in range(24)]
        lines.append('const float GANG_PAR_'+label+'[24]={'+fmt(params)+'};')
        lines.append('static const unsigned BOMB_ATTACK_'+label+'[3]={'+fmt(struct.unpack_from('<3I',exe,base+96-0x8c010000))+'};')
    lines+=['static const signed char BOMB_MOTION[22]={'+fmt([slots[s] for s in states]+[-1,slots[3]])+'};',
            'static const int BOMB_GAIT_MOTION='+str(slots[7])+';',
            'static const int BOMB_FRONT_GRAB_MOTION='+str(slots[22])+';',
            'static const unsigned char BOMB_FRAMES['+str(len(addresses))+']={'+fmt([struct.unpack_from('<H',bank,p+2)[0] for p in addresses])+'};',
            'static const unsigned BOMB_BLAST_FRAMES='+str(struct.unpack_from('<H',bank,u(0x8c1b5dd4)-0x8ca00000+2)[0])+';']
    return '\n'.join(lines)+'\n'
if __name__=='__main__':
    p=ROOT/'psp/src/bomb_source.inc'
    if '--check' in sys.argv:assert p.read_text()==header()
    else:p.write_text(header())
