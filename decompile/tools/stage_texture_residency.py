#!/usr/bin/env python3
"""Generate fixed, unchanged-quality VRAM weights from archived PSP views.

The real stage renderer supplies submitted triangles. Projected area and draw
counts are proxies for reuse, not texture bandwidth or hardware FPS. Every
fourth block of four route samples is reserved for validation, never fitting.
"""
import argparse
import hashlib
import json
import struct
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT = ROOT / 'decompile/campaign_captures/grind_square_20260923/residency'


def fnv(data):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xffffffff
    return h


def asset(city, assets=ROOT/'psp'):
    data = (assets / f'stage{city}.jgs').read_bytes()
    h = struct.unpack_from('<12I', data, 4)
    textures = [struct.unpack_from('<4H2I', data, h[5] + i * 16) for i in range(h[0])]
    batches = [struct.unpack_from('<II4H', data, h[7] + i * 16) for i in range(h[2])]
    weights = [0] * h[0]
    for i in range(h[1]):
        *_, first, count, flags, pad = struct.unpack_from('<4f4I', data, h[6] + i * 32)
        if flags & 1:
            continue
        for b in batches[first:first + count]:
            if not b[5] & 4 and b[4] < len(weights):
                weights[b[4]] += b[3]
    return dict(key=fnv(data[:h[8]]), bytes=[t[0]*t[1]+1024 for t in textures],
                old=weights, sha256=hashlib.sha256(data).hexdigest())


def pins(weights, sizes, capacity=704512):
    result = []
    for i in sorted(range(len(weights)), key=lambda i: (-weights[i]/sizes[i], i)):
        if weights[i] and sizes[i] <= capacity:
            result.append(i)
            capacity -= sizes[i]
    return result


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--capture', type=Path, default=DEFAULT)
    ap.add_argument('--assets', type=Path, default=ROOT/'psp')
    ap.add_argument('--output', type=Path, default=ROOT/'psp/src/stage_texture_usage.inc')
    args = ap.parse_args()
    capture = args.capture.resolve()
    assets = args.assets.resolve()
    samples = json.loads((capture/'texture_samples.json').read_text())['samples']
    with tempfile.TemporaryDirectory(prefix='jgr-texture-') as tmp:
        exe = Path(tmp)/'capture'
        subprocess.run(['cc','-O2','-ffp-contract=off','-Ipsp/tests/render_stubs','-Ipsp/tests/stubs',
                        'psp/tests/stage_texture_usage.c','-lm','-o',str(exe)],cwd=ROOT,check=True)
        subprocess.run([str(exe),str(capture/'texture_samples.txt'),str(capture/'texture_usage.txt')],
                       cwd=assets,check=True)
    data = {city: asset(city, assets) for city in sorted({r["city"] for r in samples})}
    for d in data.values():
        d.update(train=[[0.0]*len(d['old']) for _ in range(2)],
                 heldout=[[0.0]*len(d['old']) for _ in range(2)])
    for line in (capture/'texture_usage.txt').read_text().splitlines():
        sample,city,tex,draws,area=line.split()
        sample,city,tex=int(sample),int(city),int(tex)
        split='heldout' if (sample//4)%4==3 else 'train'
        data[city][split][0][tex]+=float(area)
        data[city][split][1][tex]+=int(draws)
    lines=['/* Generated by stage_texture_residency.py; no texture changes or runtime uploads. */',
           'typedef struct {unsigned key,count;const unsigned *weight;} StageTextureUsage;']
    report={}
    for city,d in data.items():
        area,draw=d['train'];old=d['old']
        norm=lambda v: [x/sum(v) for x in v]
        a,b,c=norm(area),norm(draw),norm(old)
        weights=[max(1,round(100000000*(.15*z+.85*(.75*x+.25*y)))) if x+y+z else 0
                 for x,y,z in zip(a,b,c)]
        before,after=pins(old,d['bytes']),pins(weights,d['bytes'])
        metrics={}
        for split in ('train','heldout'):
            metrics[split]={kind:dict(before=sum(d[split][k][t] for t in before)/sum(d[split][k]),
                                     after=sum(d[split][k][t] for t in after)/sum(d[split][k]))
                            for k,kind in enumerate(('area_fraction','draw_fraction'))}
        # Don't ship a residency set that loses aggregate held-out coverage.
        accepted=metrics['heldout']['area_fraction']['after']>=metrics['heldout']['area_fraction']['before']
        if accepted:
            lines.append(f'static const unsigned stage_texture_weight_{city}[]={{'+','.join(map(str,weights))+'};')
        report[city]=dict(asset_sha256=d['sha256'],metadata_key=d['key'],sample_count=sum(r['city']==city for r in samples),
                          accepted=accepted,old_pins=before,new_pins=after,
                          old_bytes=sum(d['bytes'][t] for t in before),new_bytes=sum(d['bytes'][t] for t in after),metrics=metrics)
    lines.append('static const StageTextureUsage stage_texture_usage[]={')
    for city,d in data.items():
        if report[city]['accepted']:
            lines.append(f'    {{0x{d["key"]:08x}u,{len(d["old"])},stage_texture_weight_{city}}},')
    lines.append('};')
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text('\n'.join(lines)+'\n')
    (capture/'texture_residency.json').write_text(json.dumps(report,indent=2)+'\n')
    for city,r in report.items():
        print(city,r['accepted'],r['metrics'])


if __name__=='__main__':
    main()
