#!/usr/bin/env python3
"""Original PLAY normal-character articulated collision spheres."""
from pathlib import Path
import struct
import sys
ROOT=Path(__file__).resolve().parents[2]
def generate():
    result=['/* Generated by player_body_assets.py: original PLAY normal collision tree. */',
            'const PlayerBodyNode PLAYER_BODY[16][20]={']
    for line in (ROOT/'decompile/chars_spec.txt').read_text().splitlines()[:16]:
        name,path,*_=line.split(':');data=(ROOT/'decompile'/path).read_bytes()
        u=lambda o:struct.unpack_from('<I',data,o)[0]
        assert data[:4]==b'PLAY'
        # The character descriptor selects the collision tree; NoiseTank has
        # a distinct later section-5 tree used for spray rendering.
        root=u(u(8)+0x6c)
        nodes=[]
        def walk(p,parent=-1):
            while p:
                kind,shape=struct.unpack_from('<2I',data,p)
                assert kind&65535 in (0,2)
                sphere=struct.unpack_from('<4f',data,shape) if kind&65535 else (0.,)*4
                bind=slice(p+12,p+48)
                pos=struct.unpack_from('<3f',data,bind.start)
                ang=struct.unpack_from('<3i',data,p+24)
                scale=struct.unpack_from('<3f',data,p+36)
                assert struct.unpack_from('<3f',data,p+48)==(0.,0.,0.),'nonzero contact anchor requires exporting +48'
                own=len(nodes);nodes.append((parent,kind>>16,sphere,pos,ang,scale))
                walk(u(p+60),own);p=u(p+64)
        walk(root);assert len(nodes)==20
        result.append('    { /* '+name+' */')
        for parent,attribute,sphere,pos,ang,scale in nodes:
            floats=lambda values:','.join(v.hex()+'f' for v in values)
            result.append('        {%d,%d,{%s},{%s},{%s},{%s}},'%(parent,attribute,floats(sphere),floats(pos),','.join(map(str,ang)),floats(scale)))
        result.append('    },')
    return '\n'.join(result+['};',''])
if __name__=='__main__':
    data=generate()
    if '--check' in sys.argv:
        assert (ROOT/'psp/src/player_body.inc').read_text()==data
        print('16 original PLAY collision trees / 320 nodes verified')
    else:print(data,end='')
