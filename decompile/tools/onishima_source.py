#!/usr/bin/env python3
"""Onishima's original parameters (1b918c) and 24 motion bindings (1b60ec)."""
from pathlib import Path
import struct,sys
ROOT=Path(__file__).resolve().parents[2]
def header():
    e=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    d=(ROOT/'decompile/afs/ENEMY/033_onisimadat.bin').read_bytes()
    values=[]
    for i in range(24):
        offset=0x1b918c-0x10000+i*4
        values.append(str(struct.unpack_from('<I',e,offset)[0]) if i<3 or i>=20 else struct.unpack_from('<f',e,offset)[0].hex()+'f')
    addresses=struct.unpack_from('<24I',e,0x1b60ec-0x10000)
    raw=sorted(addresses);frames=[struct.unpack_from('<HH',d,a-0x8ca00000)[1] for a in raw]
    return ('/* Generated by onishima_source.py from 1b918c / 1b60ec. */\n'
        +'static const float PAR_ONISHIMA[24] = {'+','.join(values)+'};\n'
        +'static const unsigned char ONISHIMA_FRAMES[24] = {'+','.join(map(str,frames))+'};\n')
if __name__=='__main__':
    p=ROOT/'psp/src/onishima_source.inc'
    if '--check' in sys.argv:assert p.read_text()==header()
    else:p.write_text(header())
