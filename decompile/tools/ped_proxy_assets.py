#!/usr/bin/env python3
"""Bake small, visual-geometry pedestrian blockers for Shibuya's bus area.

Roof polygons use the existing opaque, manifold, convex patch certificate.
Selection is spatial around authored bus placements, not global patch area.
Bus bodies deliberately approximate the inset solid body of the actual
near/far visual models; windows and limb visibility are not preserved.
No collision meshes or manually entered world coordinates are used.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

import numpy as np
import stage_visibility_assets as visibility

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'psp/src/stage_ped_proxy_data.inc'
BUS_TYPES = (0, 2)  # Shibuya's two authored parked-bus model types.


def fingerprint(data, batches):
    ov, oi = struct.unpack_from('<II', data, 36)
    key = visibility.fnv(data[:ov])
    for vo, io, nv, ni, _, _ in batches:
        key = visibility.fnv(data[ov + vo * 24:ov + (vo + nv) * 24], key)
        key = visibility.fnv(data[oi + io * 2:oi + (io + ni) * 2], key)
    return key


def placements(path):
    data = path.read_bytes()
    assert data[:4] == b'SOB1'
    count, = struct.unpack_from('<I', data, 4)
    at, result = 8, []
    for _ in range(count):
        n, = struct.unpack_from('<I', data, at)
        at += 4
        for _ in range(n):
            record = struct.unpack_from('<IIffff', data, at)
            at += 24
            if record[1] in BUS_TYPES:
                result.append(record)
    assert at == len(data)
    return result


def cfloat(value):
    return float(np.float32(value)).hex() + 'f'


def array(values):
    return '{' + ','.join(cfloat(x) for x in values) + '}'


def build():
    city_path, object_path, placement_path = [ROOT / 'psp' / p for p in
        ('stage1.jgs', 'stage1_obj.jgs', 'set1_obj.bin')]
    city, objects, batches, verts, indices = visibility.load(city_path)
    prop, prop_objects, prop_batches, prop_verts, _ = visibility.load(object_path)
    records = placements(placement_path)
    bus_positions = np.array([(r[2], r[4]) for r in records])
    roofs = []
    # Keep the original whole-plane certificate used for the shipped proxy
    # layout; disconnected-component experiments must not silently add roofs.
    for raw_area, owner, points in visibility.patches(objects, batches, verts, indices, split_components=False):
        normal = np.cross(points[1] - points[0], points[2] - points[0])
        normal /= np.linalg.norm(normal)
        center = points.mean(axis=0)
        if (abs(normal[1]) < .98 or raw_area < 500 or not 15 < center[1] < 150 or
                np.min(np.sum((bus_positions - center[[0, 2]]) ** 2, axis=1)) > 200 ** 2):
            continue
        inside = visibility.inset(points, 1.0)
        if inside is None:
            continue
        inner, area_vector = inside
        # The certifier groups a single connected patch per source plane.
        # Retain the exact contributing batch range for runtime draw gating.
        used = []
        obj = objects[owner]
        distance = points[0] @ normal
        for bi in range(obj[4], obj[4] + obj[5]):
            vo, io, _, ni, _, flags = batches[bi]
            if flags & 1:
                continue
            triangles = verts[vo + indices[io:io + ni].reshape(-1, 3)]
            if np.any(np.all(np.abs(triangles @ normal - distance) < .01, axis=1)):
                used.append(bi)
        assert used
        count = len(inner)
        center = inner.mean(axis=0)
        radius = float(np.linalg.norm(inner - center, axis=1).max()) + .1
        points4 = np.vstack((inner, inner[:1]))[:4]
        roofs.append(dict(owner=owner, count=count, points=points4.tolist(),
                          center=center.tolist(), radius=radius,
                          inverse_area=float(1.0 / np.linalg.norm(area_vector)),
                          first_batch=min(used), last_batch=max(used),
                          raw_area=float(raw_area)))
    assert 0 < len(roofs) <= 80
    bodies = []
    for kind in BUS_TYPES:
        for model in (kind, kind + len(prop_objects) // 2):
            obj = prop_objects[model]
            vv = np.concatenate([prop_verts[b[0]:b[0] + b[2]] for b in
                                 prop_batches[obj[4]:obj[4] + obj[5]] if b[2]])
            low, high = vv.min(axis=0), vv.max(axis=0)
            # Avoid wheel/roof extremities. This remains an explicit solid
            # body approximation, not an opacity certificate for windows.
            low += np.array((2., 4., 2.))
            high -= np.array((2., 4., 2.))
            assert np.all(high > low)
            bodies.append(dict(model=model, low=low.tolist(), high=high.tolist()))
    text = ['/* Generated by decompile/tools/ped_proxy_assets.py. Do not edit. */',
            'static const StagePedProxyRoof stage_ped_proxy_roofs[] = {']
    for r in roofs:
        text.append(' {' + '{' + ','.join(array(p) for p in r['points']) + '},' +
                    array(r['center']) + ',' + cfloat(r['radius']) + ',' +
                    cfloat(r['inverse_area']) + ',%u,%u,%u,%u},' %
                    (r['owner'], r['count'], r['first_batch'], r['last_batch']))
    text += ['};', 'static const StagePedProxyBody stage_ped_proxy_bodies[] = {']
    for b in bodies:
        text.append(' {' + array(b['low']) + ',' + array(b['high']) + ',%u},' % b['model'])
    text += ['};', 'static const StagePedProxyBank stage_ped_proxy_banks[] = {']
    for data, bs, kind in ((city, batches, 1), (prop, prop_batches, 2)):
        counts = struct.unpack_from('<5I', data, 4)
        text.append(' {0x%08xu,%s,%u},' %
                    (fingerprint(data, bs), ','.join(str(n) + 'u' for n in counts), kind))
    text += ['};', '']
    audit = dict(format='compiled immutable metadata', scope='Shibuya bus area',
                 roof_count=len(roofs), body_models=bodies, roofs=roofs,
                 bus_placements=records,
                 selection='Opaque horizontal patches area>=500, height15..150, within200XZ of an authored type0/type2 bus placement; inset1.0.',
                 body_approximation='Solid near/far visual bounds inset(2,4,2); windows/limbs intentionally not certified.',
                 geometry_keys={'city': '%08x' % fingerprint(city, batches),
                                'props': '%08x' % fingerprint(prop, prop_batches)},
                 source_sha256={str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                                for p in (city_path, object_path, placement_path)})
    return '\n'.join(text), audit


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--audit', type=Path)
    args = parser.parse_args()
    text, audit = build()
    if args.check:
        if OUTPUT.read_text() != text:
            raise SystemExit('pedestrian proxy metadata is stale')
    else:
        OUTPUT.write_text(text)
    if args.audit:
        args.audit.write_text(json.dumps(audit, indent=2) + '\n')
    print('Pedestrian proxies: %u certified roof patches, %u bus LOD bodies' %
          (audit['roof_count'], len(audit['body_models'])))


if __name__ == '__main__':
    main()
