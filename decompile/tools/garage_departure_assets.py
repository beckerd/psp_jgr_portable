#!/usr/bin/env python3
"""026234's original confirmation cameras and motion lengths, US garage."""
from pathlib import Path
import bisect
import struct
import sys
ROOT=Path(__file__).resolve().parents[2]
def extract():
    exe=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    dat=(ROOT/'decompile/afs/U_GARAGE/001_garagedat.bin').read_bytes()
    def u(a):
        return struct.unpack_from('<I',dat,a-0x8c800000)[0] if 0x8c800000<=a<0x8c800000+len(dat) else struct.unpack_from('<I',exe,a-0x8c010000)[0]
    def f32(v):return struct.unpack('<f',struct.pack('<f',v))[0]
    def sample(p,count,stride,frame,integer=False):
        keys=[u(p+j*stride) for j in range(count)]
        assert keys==sorted(set(keys)) and keys[0]==0
        lo=max(0,bisect.bisect_right(keys,frame)-1);hi=(lo+1)%count
        t=f32((frame-keys[lo])/(keys[hi]-keys[lo] if keys[hi]>keys[lo] else 1));g=f32(1-t)
        values=[]
        for j in range((stride-4)//4):
            fmt='<i' if integer else '<f'
            a=struct.unpack_from(fmt,dat,p-0x8c800000+lo*stride+4+j*4)[0]
            b=struct.unpack_from(fmt,dat,p-0x8c800000+hi*stride+4+j*4)[0]
            # 22f504/22f5a0: rounded FMUL followed by the original FMAC.
            value=f32(g*f32(a)+f32(t*f32(b)))
            values.append(int(value) if integer else value)
        return values
    lines=['/* Generated by garage_departure_assets.py from original US data. */']
    lengths=[];cameras=[];count=[]
    for slot in range(15):
        motion=u(u(0x8c105cd0+slot*4));cam=u(u(0x8c105dfc+slot*4))
        lengths.append(u(motion)>>16 if motion else 0)
        if not cam:
            count.append(0);cameras.append('NULL');continue
        md=u(cam);n=u(cam+4);count.append(n);cameras.append(f'DEPART_CAMERA_{slot}')
        assert u(cam+8)==0x401c1
        counts=[u(md+16+k*4) for k in range(4)]
        assert all(0<c<=n for c in counts)
        ptr=[u(md+k*4) for k in range(4)]
        lines.append(f'static const GarageDepartureKey DEPART_CAMERA_{slot}[{n}]={{')
        for k in range(n):
            values=sample(ptr[0],counts[0],16,k)+sample(ptr[1],counts[1],16,k)
            roll,fov=[sample(ptr[j],counts[j],8,k,True)[0] for j in (2,3)]
            lines.append('    {{'+','.join(v.hex()+'f' for v in values)+f'}},{roll},{fov}'+'},')
        lines.append('};')
    lines.append('static const unsigned DEPART_FRAMES[15]={'+','.join(map(str,lengths))+'};')
    lines.append('static const unsigned DEPART_CAMERA_FRAMES[15]={'+','.join(map(str,count))+'};')
    lines.append('static const GarageDepartureKey *const DEPART_CAMERAS[15]={'+','.join(cameras)+'};')
    return '\n'.join(lines)+'\n'
if __name__=='__main__':
    content=extract();path=ROOT/'psp/src/garage_departure.inc'
    if '--check' in sys.argv:
        assert path.read_text()==content;print('Original 11 departure motions/cameras verified')
    elif '--write' in sys.argv:path.write_text(content)
    else:print(content,end='')
