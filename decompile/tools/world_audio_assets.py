#!/usr/bin/env python3
"""Package unchanged world banks and the original pedestrian/profile tables.

Logical bank 16 -> SOSB 6, bank 17 -> SMSB/SMPB 2 (0e7558).
USA stages 5/6 residency is verified by flycast_world_audio_banks.lua.
"""
import argparse
import hashlib
import json
import struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
BANKS={1:('064_s_shibuya.osb','070_s_shibuya_seq.msb','076_s_shibuya_seq.mpb'),
       2:('063_s_kogane.osb','068_s_kogane_seq.msb','074_s_kogane_seq.mpb'),
       3:('062_s_benten.osb','067_s_benten_seq.msb','073_s_benten_seq.mpb'),
       5:('065_s_usa.osb','067_s_benten_seq.msb','073_s_benten_seq.mpb'),
       6:('065_s_usa.osb','067_s_benten_seq.msb','073_s_benten_seq.mpb')}
def products():
    products={};manifest={}
    for stage,names in BANKS.items():
        chunks=[(ROOT/'decompile/afs/E_SND_SE'/n).read_bytes() for n in names]
        offset=32;header=[stage]
        for b in chunks:header.extend((offset,len(b)));offset+=len(b)
        products[f'psp/worldaudio{stage}.bin']=struct.pack('<4s7I',b'WSA1',*header)+b''.join(chunks)
        manifest[str(stage)]=[dict(source=n,bytes=len(b),sha256=hashlib.sha256(b).hexdigest()) for n,b in zip(names,chunks)]
    rom=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    reactions=struct.unpack_from('<'+'h'*304,rom,0x1b9650-0x10000)[1::4]
    lines=['/* Generated by world_audio_assets.py from 1ST_READ.BIN. */',
           'static const short WORLD_NPC_REACTION[76]={'+','.join(map(str,reactions))+'};',
           'static const unsigned char WORLD_SEQUENCE_CHANNEL[17]={'+','.join(str(struct.unpack_from('<I',rom,0x1d595c-0x10000+i*28+4)[0]) for i in range(17))+'};']
    products['psp/src/world_audio_tables.inc']=('\n'.join(lines)+'\n').encode()
    lines=['/* Generated from original 1b9650 / 1b98b0. */',
           'static const NpcAudioType NPC_AUDIO_TYPES[76]={']
    for i in range(76):lines.append('    {%d,%d,%du},'%struct.unpack_from('<hhI',rom,0x1b9650-0x10000+8*i))
    lines+=['};','static const NpcAudioRoute NPC_AUDIO_ROUTES[25]={']
    for i in range(25):
        speed,reference,period=struct.unpack_from('<fhH',rom,0x1b98b0-0x10000+8*i)
        lines.append('    {%sf,%d,%d},'%(speed.hex(),reference,period))
    lines+=['};']
    products['psp/src/npc_audio_tables.inc']=('\n'.join(lines)+'\n').encode()
    lines=['/* Original 0e7558 profile +4 channel classes. */']
    profiles={0:(0x1d2df0,16),2:(0x1d303c,15),4:(0x1d3384,19),
              5:(0x1d3598,19),6:(0x1d37ac,16),7:(0x1d396c,16),
              16:(0x1d5400,49),17:(0x1d595c,17)}
    for bank,(address,count) in profiles.items():
        classes=[struct.unpack_from('<I',rom,address-0x10000+28*i+4)[0] for i in range(count)]
        assert all(c<=18 for c in classes)
        lines.append('static const unsigned char AUDIO_CLASSES_%d[]={%s};'%(bank,','.join(map(str,classes))))
    lines+=['static int audio_source_class(unsigned bank,unsigned program)','{switch(bank){']
    for bank,(_,count) in profiles.items():lines.append('case %d:return program<%d ? AUDIO_CLASSES_%d[program]:-1;'%(bank,count,bank))
    lines+=['default:return -1;}}']
    products['psp/src/audio_channel_tables.inc']=('\n'.join(lines)+'\n').encode()
    products['decompile/world_audio_manifest.json']=(json.dumps(manifest,indent=2)+'\n').encode()
    return products
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for name,b in products().items():
        path=ROOT/name
        if a.check:assert path.read_bytes()==b,name
        else:path.write_bytes(b)
        print(name,len(b))
if __name__=='__main__':main()
