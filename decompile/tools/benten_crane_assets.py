#!/usr/bin/env python3
"""Original single Benten crane: 048b64 type 46 / 0e3b6c, 500-frame motion."""
import argparse,hashlib,json,struct,subprocess,sys,tempfile
from pathlib import Path
from stage_render_assets import Source,EB,SB,tree,IDENTITY
ROOT=Path(__file__).resolve().parents[2];DEC=ROOT/'decompile'
MODEL=0x8cc53370;MOTION=0x8cd9c590;TEXTURE=0x8c1c1668;COLLIDER=0x8cd730c8

def generate(out):
 s=Source(3);records=[r for r in s.records(0x8c1ba918,46,52,70) if r['pid']==46]
 assert len(records)==1 and s.words(0x8c1bc064+46*4)[0]==MODEL and s.words(0x8c1bc294+46*4)[0]==COLLIDER
 assert s.words(MOTION)[0]>>16==500
 nodes=[]
 def walk(a,parent=-1):
  while a:
   i=len(nodes);kind,flags,mesh=struct.unpack_from('<HHI',s.image,a-EB)
   nodes.append((a,parent,kind,flags,mesh));child,a=s.words(a+60,2)
   if child:walk(child,i)
 walk(COLLIDER);assert len(nodes)==2 and [n[2] for n in nodes]==[0,6]
 f=lambda x:float(x).hex()+'f';vec=lambda v:'{'+','.join(f(x) for x in v)+'}'
 lines=['/* Generated by benten_crane_assets.py from the original US image. */','static const CranePlacement crane_placements[]={']
 for r in records:lines.append('{0x%08xu,%du,%s,{%s},%s},'%(r['address'],r['sector'],vec(r['pos']),','.join(map(str,r['ang'])),vec(r['scale'])))
 lines+=['};','static const CharPose crane_bind[2]={']
 for a,parent,kind,flags,mesh in nodes:
  p=struct.unpack_from('<3f3i3f',s.image,a+12-EB);lines.append('{.pos=%s,.ang={%s},.scl=%s},'%(vec(p[:3]),','.join(map(str,p[3:6])),vec(p[6:])))
 lines+=['};'];a,parent,kind,flags,mesh=nodes[1];vb,pb,nv,np=struct.unpack_from('<IIHH',s.image,mesh-EB)
 assert nv==16 and np==4
 verts=[struct.unpack_from('<3f',s.image,vb+12*i-EB) for i in range(nv)]
 lines+=['static const float crane_vertices[16][3]={']+[vec(v)+',' for v in verts]+['};','static const CraneTriangle crane_triangles[]={'];tris=[]
 for j in range(np):
  ix,fl,kinds=s.words(pb+j*36+24,3);count=fl&65535;ids=struct.unpack_from('<%dh'%(count+2),s.image,ix-EB);wind=bool(fl&0x40000000)
  for k in range(count):
   order=(ids[k],ids[k+1 if wind else k+2],ids[k+2 if wind else k+1]);flags=(1 if fl&0x80000000 else 0)|(0 if wind else 2)
   tris.append((order,kinds>>16,kinds&65535,flags));lines.append('{{%s},%du,%du,%du},'%(','.join(map(str,order)),kinds>>16,kinds&65535,flags));wind=not wind
 lines+=['};'];lights=[struct.unpack_from('<8f',s.exe,0x8c175d90+i*32-EB) for i in range(46)]
 lines+=['static const float crane_lights[46][8]={']+[vec(v)+',' for v in lights]+['};','']
 (out/'benten_crane_data.inc').write_text('\n'.join(lines))
 with tempfile.TemporaryDirectory(prefix='jgr-crane-tex-') as tmp:
  tmfile=Path(tmp)/'tex.json';subprocess.run([sys.executable,'tools/static_texmap.py','extracted/1ST_READ.BIN','3',str(tmfile)],cwd=DEC,check=True,stdout=subprocess.DEVNULL)
  tm=json.loads(tmfile.read_text());mapping=tm['texlists'][str(TEXTURE)];tx=Path(tmp)/'textures.bin';tx.write_bytes(b''.join((DEC/p).read_bytes() for p in tm['packs']))
  row=f'crane:afs/STAGE3/000_st3dat.bin:{tx}:0,0,0,0:rawat:{SB:x}:{MODEL:x}:{MOTION:x}:texmap='+','.join(map(str,mapping))+':lighting=1:cull=none'
  subprocess.run([sys.executable,'tools/jgc_convert.py',str(out/'benten_crane.jgc'),'--motions=1','--texmax=512','--source-material=1','--source-environment=1',row],cwd=DEC,check=True)
 side=json.loads((ROOT/'psp/stage3.jgs.map.json').read_text());assert MODEL-SB not in {v[0] for v in side}
 meta=dict(placements=records,frames=500,loop_frames=499,collision_triangles=len(tris),vertices=verts,triangles=tris,texture_indices=mapping,
  source_sha256=hashlib.sha256(s.data).hexdigest(),functions=['048b64','0e3b6c','0e3ce0','0e3e4c'])
 (out/'benten_crane_assets.json').write_text(json.dumps(meta,indent=2)+'\n')

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
 with tempfile.TemporaryDirectory(prefix='jgr-crane-') as tmp:
  out=Path(tmp);generate(out)
  for path in out.iterdir():
   dest=ROOT/'psp'/('src' if path.suffix=='.inc' else '')/path.name
   if a.check:assert dest.read_bytes()==path.read_bytes(),path.name
   else:dest.write_bytes(path.read_bytes())
if __name__=='__main__':main()
