#!/usr/bin/env python3
"""Dog controller literals and complete motion table from the US executable."""
from pathlib import Path
import argparse, struct
ROOT=Path(__file__).resolve().parents[2]

def generated():
    exe=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    bank=(ROOT/'decompile/afs/ENEMY/005_inudat.bin').read_bytes()
    def word(a):return struct.unpack_from('<I',exe,a-0x8c010000)[0]
    def floats(a,n):return struct.unpack_from('<%df'%n,exe,a-0x8c010000)
    def literal(v):
        s=format(v,'.10g')
        return s+('f' if '.' in s or 'e' in s else '.f')
    pointers=[];a=0x8c1b5c74
    while word(a):pointers.append(word(a));a+=4
    valid=sorted(p for p in pointers if p!=0xffffffff)
    mapping=[valid.index(p) if p in valid else -1 for p in pointers]
    frames=[struct.unpack_from('<H',bank,p-0x8ca00000+2)[0] for p in valid]
    params=[word(0x8c1ba444+4*i) if i<3 or i>=20 else floats(0x8c1ba444+4*i,1)[0] for i in range(24)]
    lines=['/* Generated by decompile/tools/dog_source.py; US 1ST_READ.BIN. */',
           'static const float PAR_T2[24]={'+','.join(map(literal,params))+'};',
           'static const signed char DOG_MOTIONS[]={'+','.join(map(str,mapping))+'};',
           'static const unsigned char DOG_CLIP_FRAMES[]={'+','.join(map(str,frames))+'};']
    for name,a,n in [('DOG_CAPSULE',0x8c1ba208,7),('DOG_RELEASE',0x8c1ba4b8,6)]:
        lines.append('static const float '+name+'[]={'+','.join(map(literal,floats(a,n)))+'};')
    lines.append('static const int DOG_ATTACK[3]={'+','.join(str(word(0x8c1ba4a4+i*4)) for i in range(3))+'};')
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    p=ROOT/'psp/src/dog_source.inc';s=generated()
    if args.check:assert p.read_text()==s
    else:p.write_text(s)
    print('Dog source constants and all 14 semantic motions verified')
