#!/usr/bin/env python3
"""Extract original MANATEE attenuation/pan tables; no fitted gain curves."""
from pathlib import Path
import argparse
import math
ROOT=Path(__file__).resolve().parents[2]
def generate():
    driver=(ROOT/'decompile/extracted/JETRADIO/MANATEE.DRV').read_bytes()
    assert driver[:4]==b'SDRV'
    lines=['/* Generated by audio_spatial_assets.py from supplied MANATEE.DRV. */']
    for name,address,n in [('MANATEE_TL',0x4f1c,256),('MANATEE_SEND',0x501c,64),
                           ('MANATEE_PAN',0x505c,128),('MANATEE_PAN_BASE',0x50dc,32)]:
        values=driver[32+address:32+address+n];assert len(values)==n
        lines.append(f'static const unsigned char {name}[{n}]={{')
        lines.extend('    '+','.join(str(v) for v in values[i:i+16])+',' for i in range(0,n,16));lines.append('};')
    # Local Flycast sgc_if.cpp Init(): AICA's x.15 logarithmic attenuator.
    # Generated offline so no transcendentals run on PSP's audio thread.
    values=[int(32768/math.pow(2,i/16)) for i in range(255)]+[0]
    lines.append('static const unsigned short AICA_TL_GAIN[256]={')
    lines.extend('    '+','.join(str(v) for v in values[i:i+16])+',' for i in range(0,256,16));lines.append('};')
    return '\n'.join(lines)+'\n'
if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    out=ROOT/'psp/src/audio_spatial_tables.inc';text=generate()
    if args.check:assert out.read_text()==text
    else:out.write_text(text)
