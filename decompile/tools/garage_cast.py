#!/usr/bin/env python3
"""Original US garage residents, placements, texture lists and dance motions.

02263c uses tables 105b68/105ba4/105c1c/105c58/105c94. Texture-list
initializers immediately follow each NJS_TEXLIST in the executable; their
pointers name GBIX records in U_GARAGE garagetxr at link base 8c800000.
"""
from pathlib import Path
import struct
import subprocess
import sys
ROOT=Path(__file__).resolve().parents[2]
DEC=ROOT/'decompile'
B=0x8c800000

def extract():
    exe=(DEC/'extracted/1ST_READ.BIN').read_bytes()
    dat=(DEC/'afs/U_GARAGE/001_garagedat.bin').read_bytes()
    txr=(DEC/'afs/U_GARAGE/002_garagetxr.bin').read_bytes()
    u=lambda a:struct.unpack_from('<I',exe,a-0x8c010000)[0]
    v=lambda a:struct.unpack_from('<I',dat,a-B)[0] if B<=a<B+len(dat) else u(a)
    offsets=[];o=0
    while True:
        o=txr.find(b'GBIX',o)
        if o<0:break
        offsets.append(o);o+=8
    def texmap(tl):
        return [offsets.index(u(tl+8+k*4)-B) for k in range(u(tl+4))]
    names='Beat Gum Tab Combo Slate Mew Garam Piranha YoYo Cube TrophyS TrophyK TrophyB TrophyAll Pots'.split()
    rows=[];meta=[]
    def row(name,model,mots,tm,lighting):
        return (f'{name}:afs/U_GARAGE/001_garagedat.bin:afs/U_GARAGE/002_garagetxr.bin:'
                f'0,0,0,0:rawat:{B:x}:{model:x}:'+','.join(f'{a:x}' for a in mots)+
                ':texmap='+','.join(map(str,tm))+f':lighting={lighting}')
    rows.append(row('Garage',v(B),[0],texmap(0x8c10e410),1))
    room_motion=v(B+4)
    assert v(room_motion+4)==100 and v(room_motion+8)==0x20003
    # All 19 MDATA2 records are empty: the room clock does not animate it.
    assert dat[v(room_motion)-B:v(room_motion)-B+19*16]==bytes(19*16)
    for c,name in enumerate(names):
        pos=v(u(0x8c105b68+c*4));model=v(u(0x8c105ba4+c*4))
        shadow=v(u(0x8c105c1c+c*4));mots=[v(u(a+c*4)) for a in (0x8c105c58,0x8c105c94)]
        tm=texmap(u(0x8c105aec+c*4));primary=len(rows)
        # 02263c uses cel mode 0 for dancing residents, normal mode 1 for
        # the four awards. Preserve original normals/materials at export;
        # the garage's runtime lighting is not a city-light bake.
        # 026234 uses the same primary/secondary trees with the confirmation
        # motion at 105cd0, not either of the two resident dance clips.
        departure=v(u(0x8c105cd0+c*4))
        rows.append(row(name,model,mots+([departure] if departure else []),tm,1 if 10<=c<=13 else 2));secondary=-1
        # The second tree is a modifier volume, not an ordinary chunk mesh.
        # The body's own original black outline strips are already included.
        # garage_shadow_assets.py exports these separately with their signed
        # strips and secondary bind transforms; never export empty JGC meshes.
        tr=struct.unpack_from('<3f3i',dat,pos-B+8) if pos else (0.,0.,0.,0,0,0)
        assert tr[3]==tr[5]==0,'new rotation axis needs full TRS'
        frames=[v(a)>>16 if a else 0 for a in mots]
        meta.append((primary,secondary,*tr[:3],tr[4],*frames))
    special_prop=len(rows)
    # 0221b8 / 025924 / 0f63f0 draw this extra original object separately
    # from both the room tree and dancing residents. The special cameras
    # target it; omitting it leaves an empty wall in the departure selector.
    rows.append(row('SpecialDeparture',v(B+0x264),[0],texmap(0x8c10e2b4),1))
    lines=['/* Generated by garage_cast.py from original US data. */',
           'static const GarageResident GARAGE_RESIDENTS[15] = {']
    for primary,secondary,x,y,z,yaw,f0,f1 in meta:
        lines.append('    {'+f'{primary},{secondary},'+','.join(v.hex()+'f' for v in (x,y,z))+f',{yaw},{{{f0},{f1}}}'+'},')
    lines+=['};','']
    lines.append(f'static const unsigned GARAGE_SPECIAL_PROP={special_prop};')
    # 049298/0493cc are separate from the unlockable resident 14. Keep
    # their original room placement, motion and texture lists as well.
    pet_models=[];pet_frames=[]
    for k,(name,tl) in enumerate((('GarageDog',0x8c10e55c),
                                ('GarageDogReturned',0x8c10e58c),
                                ('GarageStoryProp',0x8c10e284))):
        model=v(B+0xa0+k*4);motion=v(B+0xac+k*4)
        pet_models.append(len(rows));pet_frames.append(v(motion)>>16)
        rows.append(row(name,model,[motion],texmap(tl),2 if k<2 else 1))
    x,y,z,rx,ry,rz=struct.unpack_from('<3f3i',dat,v(B+0x98)-B+8)
    assert rx==rz==0
    lines.append('static const unsigned GARAGE_PET_MODELS[3]={'+','.join(map(str,pet_models))+'};')
    lines.append('static const unsigned GARAGE_PET_FRAMES[3]={'+','.join(map(str,pet_frames))+'};')
    lines.append('static const float GARAGE_PET_POSITION[3]={'+','.join(a.hex()+'f' for a in (x,y,z))+'};')
    lines.append(f'static const int GARAGE_PET_YAW={ry+0x444};')
    for name,addr in (('PROGRAM',0x8c10e0f0),('TICK',0x8c10e12c)):
        lines.append(f'static const unsigned GARAGE_VOICE_{name}[15]={{'+','.join(str(u(addr+4*k)) for k in range(15))+'};')
    # 800004 is the ROOM OBJECT motion, not a camera. Camera task 0229c0
    # selects 800008 / 80000c and reads NJS_MDATA4 position/target/roll/FOV.
    for path,cell in enumerate((B+8,B+12)):
        header=v(cell);md=v(header);n=v(header+4)
        assert v(header+8)==0x401c1
        ptrs=[v(md+k*4) for k in range(4)]
        counts=[v(md+16+k*4) for k in range(4)]
        assert counts==[n,n,2,2]
        assert all(v(ptrs[2]+k*8+4)==0 for k in range(2)), 'nonzero camera roll'
        assert v(ptrs[3]+4)==v(ptrs[3]+12), 'animated camera FOV'
        lines.append(f'static const float GARAGE_CAMERA_{path}[{n}][6] = {{')
        for k in range(n):
            assert v(ptrs[0]+k*16)==v(ptrs[1]+k*16)==k
            values=struct.unpack_from('<3f',dat,ptrs[0]-B+k*16+4)+struct.unpack_from('<3f',dat,ptrs[1]-B+k*16+4)
            lines.append('    {'+','.join(x.hex()+'f' for x in values)+'},')
        lines.append('};')
        lines.append(f'static const unsigned GARAGE_CAMERA_FOV_{path}={v(ptrs[3]+4)};')
    for path,addr in enumerate((0x8c10dc70,0x8c10dc90)):
        values=struct.unpack_from('<8f',exe,addr-0x8c010000)
        lines.append(f'static const float GARAGE_STOPS_{path}[8]={{'+','.join(x.hex()+'f' for x in values)+'};')
    order=[u(0x8c10e06c+k*4) for k in range(15)]
    lines.append('static const unsigned char GARAGE_SELECT_ORDER[15]={'+','.join(str(order.index(k)) for k in range(15))+'};')
    lines.append('static const float GARAGE_SELECT_CAMERA[15][6]={')
    for k in range(15):
        values=tuple(x for a in (0x8c10dff4,0x8c10e030) for x in struct.unpack_from('<3f',dat,v(u(a+k*4))-B+8))
        lines.append('    {'+','.join(x.hex()+'f' for x in values)+'},')
    lines.append('};')
    lines.append(f'static const unsigned GARAGE_SELECT_FOV={u(0x8c1057ac+0x1c)};')
    # 0f5e0c / 0f63f0: the story's Bantam/Grind departure is a separate
    # two-character selector, not the regular fifteen-slot camera carousel.
    lines.append('static const unsigned char GARAGE_SPECIAL_CHAR[2]={'+','.join(str(u(0x8c21a790+4*k)) for k in range(2))+'};')
    lines.append('static const float GARAGE_SPECIAL_CAMERA[2][6]={')
    for k in range(2):
        values=tuple(x for a in (0x8c21a780,0x8c21a788) for x in struct.unpack_from('<3f',dat,v(u(a+4*k))-B+8))
        lines.append('    {'+','.join(x.hex()+'f' for x in values)+'},')
    lines.append('};')
    # 02666c uses these actual image lists, not approximate atlas rectangles.
    # Keep every quad; mirrored arrows have bit 0x10 in the entry attributes.
    quads=[];ranges=[]
    headers=[v(B+0x3a0),v(B+0x360),v(B+0x374)]
    headers += [v(u(0x8c10df7c+k*4)) if u(0x8c10df7c+k*4) else 0 for k in range(15)]
    for header in headers:
        start=len(quads)
        if header:
            ep,n=v(header),v(header+4)
            assert struct.unpack_from('<3fi2f',dat,header-B+8)==(0.,0.,0.,0,1.,1.)
            for k in range(n):
                p=ep+k*64-B
                slot,flags,x,y,w,h,rot,z,pu,pv,*tail=struct.unpack_from('<HH4fhh2f4I4f',dat,p)
                assert rot==0 and len(set(tail[:4]))==1 and flags in (0x2580,0x2590)
                u0,v0,u1,v1=tail[4:]
                if flags&0x10:u0,u1=u1,u0
                quads.append((slot,tail[0],x,y,w,h,u0,v0,u1,v1))
        ranges.append((start,len(quads)-start))
    lines.append('static const GarageQuad GARAGE_QUADS[]={')
    for slot,color,*xyuv in quads:
        lines.append('    {'+f'{slot},0x{color:08x}u,'+','.join(x.hex()+'f' for x in xyuv)+'},')
    lines.append('};')
    lines.append('static const unsigned char GARAGE_LISTS[][2]={'+','.join('{%d,%d}'%r for r in ranges)+'};')
    lines.append('')
    return '\n'.join(rows)+'\n','\n'.join(lines)

if __name__=='__main__':
    spec,inc=extract()
    if '--check' in sys.argv:
        assert (DEC/'garage_spec.txt').read_text()==spec
        assert (ROOT/'psp/src/garage_cast.inc').read_text()==inc
        print('US garage: all 15 residents, source textures, placements and dance lengths verified')
    elif '--bake' in sys.argv:
        subprocess.run([sys.executable,'tools/jgc_convert.py','../psp/garage.jgc',
                        '--spec=garage_spec.txt','--source-material=1','--source-environment=1','--texmax=256'],cwd=DEC,check=True)
    elif '--write' in sys.argv:
        (DEC/'garage_spec.txt').write_text(spec)
        (ROOT/'psp/src/garage_cast.inc').write_text(inc)
    else:print(inc if '--inc' in sys.argv else spec,end='')
