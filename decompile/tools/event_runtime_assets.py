#!/usr/bin/env python3
"""Runtime mesh bindings for original EVENT actors, separate from source import.

Typed rival actors in mission context use PLAY variants selected by type % 3;
all other actors retain the imported ENEMY/EVENT root and material bindings.
"""
import argparse,json,struct,subprocess,sys
from pathlib import Path
from event_assets import catalog
from cutscene_sources import ROOT,DEC,executable
from result_camera_assets import MODELS
PSP=ROOT/'psp'

def rival_assets(bake):
    rows=[];spec=(DEC/'chars_spec.txt').read_text().splitlines()
    for kind,character in ((18,11),(19,10),(20,12)):
        model=MODELS[character];name,dat,tex=spec[model].split(':')[:3]
        d=(DEC/dat).read_bytes();t=(DEC/tex).read_bytes()
        u=lambda b,o:struct.unpack_from('<I',b,o)[0]
        header=u(d,8);th=u(t,8);variant=kind%3
        assert u(d,header)==u(t,th)==character
        # Source PLAY +08/+58 and PTEX +08/+58 are corresponding variants.
        for mouth,field in ((False,8),(True,0x58)):
            root=u(d,header+field+variant*4);tl=u(t,th+field+variant*4)
            assert root and tl
            index={};at=0
            while (at:=t.find(b'GBIX',at))>=0:index[at]=len(index);at+=8
            table=u(t,4)
            while u(t,table) and u(t,table)!=tl:table+=8
            assert u(t,table)==tl
            remap=[index[u(t,u(t,table+4)+4*j)] for j in range(u(t,tl+4))]
            motions=[u(d,u(d,header+0x68)+4*j) for j in range(3)] if mouth else []
            asset=f'eventplay{kind:02d}'+('_mouth' if mouth else '')+'.jgc'
            if bake:
                description=f'{name}:{dat}:{tex}:0,0,0,0:rawat:0:{root:x}:'+(','.join(f'{v:x}' for v in motions) or '0')
                description+=':texmap='+','.join(map(str,remap))+':lighting=2'
                subprocess.run([sys.executable,'tools/jgc_convert.py',str(PSP/asset),'--toon=1','--source-material=1','--source-environment=1',f'--motions={len(motions)}',description],cwd=DEC,check=True,stdout=subprocess.DEVNULL)
            rows.append(dict(type=kind,character=character,variant=variant,mouth=mouth,source=dat,texture=tex,root=root,texlist=tl,motions=motions,asset=asset))
    return rows

def bindings(events):
    lines=['/* Generated by event_runtime_assets.py; original root/texlist identities. */']
    for event in events:
        if not event.get('models'):continue
        id=event['id'];lines.append(f'static const SceneModelBinding EVENT_MODELS_{id}[]={{')
        for model in event['models']:
            lines.append('    {%d,0x%xu,0x%xu,%du,"%s"},'%(model.get('type',-1),model['root'],model['texlist'],model['flags'],model['asset']))
        lines.append('};')
    lines.append('static inline const SceneModelBinding *scene_model_bindings(int id,unsigned *count)\n{\n    switch(id) {')
    for event in events:
        alias=event['asset_descriptor'];owner=events[alias]
        if owner.get('models'):lines.append(f'    case {event["id"]}:*count={len(owner["models"])};return EVENT_MODELS_{alias};')
    lines+=['    default:*count=0;return NULL;','    }','}','']
    return '\n'.join(lines)

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--bake',action='store_true');ap.add_argument('--check',action='store_true');args=ap.parse_args()
    events=catalog();rows=rival_assets(args.bake)
    for path,data in [(PSP/'src/scene_models.inc',bindings(events)),(PSP/'eventplay.json',json.dumps(rows,indent=2)+'\n')]:
        if args.check:assert path.read_text()==data,path
        else:path.write_text(data)
    for row in rows:assert (PSP/row['asset']).read_bytes()[:4] in (b'JGC2',b'JGC3')
    print('170 EVENT model bindings and six original PLAY variant/mouth banks verified')
if __name__=='__main__':main()
