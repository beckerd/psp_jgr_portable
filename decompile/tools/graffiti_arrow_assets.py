#!/usr/bin/env python3
"""03e6f8/03e8a4 graffiti arrows: original PLAYER effect slots 2 and 17."""
from pathlib import Path
import argparse
import struct
import subprocess
import sys
import tempfile

ROOT=Path(__file__).resolve().parents[2]

def skaters():
    rows={}
    for path in sorted((ROOT/'decompile/afs/PLAYER').glob('*.bin')):
        data=path.read_bytes()
        if data[:4]!=b'PLAY':continue
        u=lambda a:struct.unpack_from('<I',data,a)[0]
        table=u(8);character=u(table);descriptor=u(table+0x74) # 0c7cfc / 0c7f74
        assert character not in rows and 0<=character<16 and descriptor
        rows[character]=(path.name,descriptor,struct.unpack_from('<6f',data,descriptor+0x40))
    assert set(rows)==set(range(16))
    return rows

def skater_header():
    rows=skaters();text=['/* Original PLAY +74 graffiti descriptors; generated by graffiti_arrow_assets.py. */',
                        'static const float SKATER_ARROW[16][6] = {']
    for i,(path,address,values) in sorted(rows.items()):
        text.append('    {'+','.join(v.hex()+'f' for v in values)+'}, /* '+str(i)+' '+path+' +'+hex(address)+' */')
    return '\n'.join(text+['};',''])

def bake(out):
    exe=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    data=(ROOT/'decompile/afs/PLAYER/016_player_effect_dat.bin').read_bytes()
    rows=[]
    for name,slot in [('Optional',2),('Required',17)]:
        obj=struct.unpack_from('<I',exe,0x182fe8-0x10000+slot*4)[0]
        motion=struct.unpack_from('<I',exe,0x18308c-0x10000+slot*4)[0]
        kind,frames=struct.unpack_from('<HH',data,motion-0x8c8e1000)
        assert (kind,frames)==(0x15,120)
        rows.append(f'GraffitiArrow{name}:afs/PLAYER/016_player_effect_dat.bin:afs/PLAYER/017_player_effect_txr.bin:0,0,0,0:rawat:8c8e1000:{obj:x}:{motion:x}')
    subprocess.run([sys.executable,'tools/jgc_convert.py',str(out),'--nolight=1',
                    '--source-material=1','--source-environment=1',*rows],cwd=ROOT/'decompile',check=True)

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    target=ROOT/'psp/tagarrows.jgc'
    if args.check:
        with tempfile.TemporaryDirectory(prefix='jgr-tag-arrows-') as tmp:
            out=Path(tmp)/target.name;bake(out);assert out.read_bytes()==target.read_bytes()
        assert (ROOT/'psp/src/graffiti_arrow_skater.inc').read_text()==skater_header()
    else:
        bake(target)
        (ROOT/'psp/src/graffiti_arrow_skater.inc').write_text(skater_header())

if __name__=='__main__':main()
