#!/usr/bin/env python3
"""Grind Square 0f5adc light strips and 0f7fe8 elevators, original US data."""
import argparse,hashlib,json,struct,subprocess,sys,tempfile
from pathlib import Path
from stage_render_assets import Source,tree,IDENTITY,EB,SB
import ninjalib as nl
from pvr_decode import decode
ROOT=Path(__file__).resolve().parents[2];DC=ROOT/'decompile'
LIGHT_TYPES=(*range(10),13,25,34)
def generate(out,baseline_path=None):
 s=Source(6);tm=json.loads((DC/'stage6_texmap.json').read_text());records=s.records(0x8c20ae08,81,52,36)
 vec=lambda v:'{'+','.join(float(x).hex()+'f' for x in v)+'}'
 lines=['/* Generated by grind_props_assets.py from the original US image. */']
 lift=[r for r in records if r['pid']==10];assert len(lift)==2
 lines+=['static const GrindPlacement grind_placements[]={']
 for r in lift:lines.append('{%s,{%s},%s},'%(vec(r['pos']),','.join(map(str,r['ang'])),vec(r['scale'])))
 lines+=['};']
 # Collision trees consume the same six motion channels, but retain their
 # own bind poses. Body type 4 is an event box, never solid triangles.
 def nodes(root):
  rows=[]
  def walk(a,parent=-1):
   while a:
    i=len(rows);kind,flags,mesh=struct.unpack_from('<HHI',s.image,a-EB)
    rows.append((a,parent,kind,flags,mesh));child,a=s.words(a+60,2)
    if child:walk(child,i)
  walk(root);return rows
 floor=nodes(0x8cc6a594);body=nodes(s.words(0x8c20b5bc+40)[0]);assert len(floor)==6 and len(body)==5
 for name,rows in [('floor',floor),('body',body)]:
  lines+=['static const CharPose grind_'+name+'_bind[]={']
  for a,parent,kind,flags,mesh in rows:
   p=struct.unpack_from('<3f3i3f',s.image,a+12-EB)
   lines.append('{.pos=%s,.ang={%s},.scl=%s},'%(vec(p[:3]),','.join(map(str,p[3:6])),vec(p[6:])))
  lines+=['};','static const int grind_'+name+'_parents[]={'+','.join(str(r[1]) for r in rows)+'};']
 triangles=[]
 for bone,(a,parent,kind,flags,mesh) in enumerate(floor):
  if kind!=6:continue
  vb,pb,nv,np=struct.unpack_from('<IIHH',s.image,mesh-EB)
  for j in range(np):
   ix,fl,kinds=s.words(pb+j*36+24,3);count=fl&65535;ids=struct.unpack_from('<%dh'%(count+2),s.image,ix-EB);wind=bool(fl&0x40000000)
   for k in range(count):
    order=(ids[k],ids[k+1 if wind else k+2],ids[k+2 if wind else k+1]);flags=(1 if fl&0x80000000 else 0)|(0 if wind else 2)
    vertices=[struct.unpack_from('<3f',s.image,vb+12*v-EB) for v in order]
    triangles.append(dict(bone=bone,vertices=vertices,surface=kinds>>16,mask=kinds&65535,flags=flags));wind=not wind
 lines+=['static const GrindTriangle grind_triangles[]={']
 for t in triangles:lines.append('{%s,%du,%du,%du,%du},'%(vec([x for v in t['vertices'] for x in v]),t['bone'],t['surface'],t['mask'],t['flags']))
 lines+=['};'];assert body[0][2]==4 and all(r[2]==0 for r in body[1:])
 box=struct.unpack_from('<24f',s.image,body[0][4]-EB)
 lines+=['static const float grind_box[24]='+vec(box)+';']
 # The light bands are separate DYN meshes, not a tint of the floor.
 # Preserve source UV animation schedules (0c45d8) in compact draw metadata.
 b=nl.JgsBuilder();nl.MAXEDGE=120.;nl.BAKED_LIGHT=None;light_records=[]
 anim_ptrs=[0x8c0f51fc+i*16 for i in range(10)]+[0x8c0f52ac,0x8c0f535c,0x8c0f53f4]
 for r in records:
  if r['pid'] not in LIGHT_TYPES:continue
  ty=r['pid'];root=s.words(0x8c20b37c+ty*4)[0];tl=s.words(0x8c20b40c+ty*4)[0];mapping=tm['texlists'][str(tl)]
  first=len(b.objs)
  for n,m in tree(s,root,nl.mmul(nl.placement_matrix(r['pos'],r['ang']),nl.mscale(*r['scale']))):
   if n['model'] and not n['ev']&8:b.add_model(s.image,n['model'],EB,m,lambda slot:mapping[slot],light=False,source_material=True)
  animation=s.words(anim_ptrs[LIGHT_TYPES.index(ty)])[0];ptr,n=s.words(animation,2);assert n==1
  slot,keys,count,clock=s.words(ptr,4);assert count==8 and slot==0
  times=[];at=0
  for k in range(count):
   u,v,dt,_=struct.unpack_from('<2f2I',s.image,keys+16*k-EB);assert u==0 and v==(30 if k<7 else -210)
   at+=dt;times.append(at)
  light_records.append(dict(**r,first=first,count=len(b.objs)-first,texture=mapping[slot],times=times,period=at+1))
 images=[]
 for pack in tm['packs']:
  data=(DC/pack).read_bytes();p=0
  while True:
   p=data.find(b'GBIX',p)
   if p<0:break
   q=data.find(b'PVRT',p+8,p+64);length=struct.unpack_from('<I',data,q+4)[0]
   images.append(decode(data[q:q+length+8]) if len(images) in b.used else None);p+=8
 counts=nl.write_jgs(out/'grind_lights.jgs',b,images,texmax=512);texids={t:i for i,t in enumerate(sorted(b.used))}
 lines+=['static const GrindLight grind_lights[]={']
 for r in light_records:lines.append('{%du,%du,%du,%du,{%s},%s,%du},'%(r['first'],r['count'],texids[r['texture']],r['period'],','.join(map(str,r['times'])),vec(r['pos']),10 if r['pid']<10 else 2))
 lines+=['};',''];(out/'grind_props_data.inc').write_text('\n'.join(lines))
 with tempfile.TemporaryDirectory(prefix='grind-tex-') as tmp:
  tx=Path(tmp)/'tex.bin';tx.write_bytes(b''.join((DC/p).read_bytes() for p in tm['packs']));rows=[]
  for lod,(rt,tt) in enumerate(((0x8c20b37c,0x8c20b40c),(0x8c20b49c,0x8c20b52c))):
   root=s.words(rt+40)[0];mapping=tm['texlists'][str(s.words(tt+40)[0])]
   rows.append(f'lift{lod}:afs/STAGE6/000_st6dat.bin:{tx}:0,0,0,0:rawat:{SB:x}:{root:x}:8cc7e208:texmap='+','.join(map(str,mapping))+':lighting=1:cull=none')
  subprocess.run([sys.executable,'tools/jgc_convert.py',str(out/'grind_lifts.jgc'),'--motions=1','--texmax=512','--source-material=1','--source-environment=1',*rows],cwd=DC,check=True)
 # Retire only the two legacy elevator event boxes, preserving all world
 # triangles and their source patch IDs. The live floor provider replaces them.
 old=Path(baseline_path or DC/'campaign_captures/grind_square_20260923/baseline/stage6.col').read_bytes();n,off=struct.unpack_from('<II',old,4)
 ids=[i for i in range(n) if struct.unpack_from('<H',old,16+i*44+42)[0]==2];assert len(ids)==24 and ids==list(range(n-24,n))
 data=struct.pack('<4sIII',b'COL1',n-24,off-24*44,0x31535043)+old[16:16+(n-24)*44]+old[off:]
 (out/'stage6.col').write_bytes(data)
 report=dict(lifts=lift,lights=light_records,light_counts=counts,floor_triangles=triangles,source_sha256=hashlib.sha256(s.data).hexdigest(),frames=226,removed_static_triangles=24)
 (out/'grind_props.json').write_text(json.dumps(report,indent=2)+'\n')
 print('Grind props:',len(lift),'lifts,',len(light_records),'light strips;',counts,'light geometry;',len(triangles),'moving floor triangles per lift')
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--baseline',type=Path,help='Regenerated pre-retirement collision input');a=p.parse_args()
 with tempfile.TemporaryDirectory(prefix='grind-props-') as tmp:
  out=Path(tmp);generate(out,a.baseline)
  for f in out.iterdir():
   dst=ROOT/'psp'/('src' if f.suffix=='.inc' else '')/f.name
   if a.check:assert dst.read_bytes()==f.read_bytes(),f.name
   else:dst.write_bytes(f.read_bytes())
if __name__=='__main__':main()
