#!/usr/bin/env python3
"""Bantam agents: original 07ad7c/07b104 movement, attacks and motions."""
from pathlib import Path
import struct,sys
from enemy_motion_map import motion_headers
ROOT=Path(__file__).resolve().parents[2]
def header():
    exe=(ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    bank=(ROOT/'decompile/afs/ENEMY/007_killerdat.bin').read_bytes()
    # The original agent uses exactly the Keikan state and animation handlers.
    assert exe[0x1b7bb8-0x10000:0x1b7bb8-0x10000+76]==exe[0x1b72d8-0x10000:0x1b72d8-0x10000+76]
    assert exe[0x1b79f0-0x10000:0x1b79f0-0x10000+80]==exe[0x1b7328-0x10000:0x1b7328-0x10000+80]
    pointers=struct.unpack_from('<33I',exe,0x1b5cc8-0x10000)
    addresses=motion_headers(bank,12,0x8ca00000)
    slots=[addresses.index(p-0x8ca00000) if p-0x8ca00000 in addresses else -1 for p in pointers]
    if slots[11]<0:slots[11]=slots[9]
    states=[11,23,8,20,12,13,14,15,9,0,18,19,5,16,17,4,21,21,19,16]
    assert all(slots[s]>=0 for s in states+[7,22])
    frames=[struct.unpack_from('<H',bank,p+2)[0] for p in addresses]
    params=[struct.unpack_from('<I' if i<3 or i>=20 else '<f',exe,0x1b7b44-0x10000+4*i)[0] for i in range(24)]
    fmt=lambda xs:','.join(str(v) if isinstance(v,int) else v.hex()+'f' for v in xs)
    return ('/* Generated by killer_source.py: original 1b7b44/1b7ba4/1b5cc8. */\n'
      +'static const float PAR_T3[24]={'+fmt(params)+'};\n'
      +'static const signed char KILLER_MOTION[20]={'+fmt([slots[s] for s in states])+'};\n'
      +'static const int KILLER_GAIT_MOTION='+str(slots[7])+';\n'
      +'static const int KILLER_FRONT_GRAB_MOTION='+str(slots[22])+';\n'
      +'static const unsigned char KILLER_FRAMES['+str(len(frames))+']={'+fmt(frames)+'};\n'
      +'static const unsigned KILLER_ATTACK[3]={'+fmt(struct.unpack_from('<3I',exe,0x1b7ba4-0x10000))+'};\n')
if __name__=='__main__':
    p=ROOT/'psp/src/killer_source.inc'
    if '--check' in sys.argv:assert p.read_text()==header()
    else:p.write_text(header())
