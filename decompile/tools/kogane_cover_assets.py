#!/usr/bin/env python3
"""0399a0: mission +e0 bit 0 selects the closed sector-22 manhole.

The alternate F list adds original model 72; the alternate DYN list removes
nine construction objects. Preserve both collision variants independently.
"""
import argparse,json,struct,subprocess,sys,tempfile
from pathlib import Path
from stage_render_assets import Source,SB,EB,ROOT,DC
import ninjalib as nl

def removed_records():
    s=Source(2)
    def records(table):
        return s.records(table,1,40,91)
    opened=records(0x8c108668);closed=records(0x8c108684)
    key=lambda r:(r['pid'],r['pos'],r['ang'])
    result=[r for r in opened if key(r) not in {key(c) for c in closed}]
    assert len(result)==9
    return result

def cover_triangles():
    s=Source(2);read=lambda fmt,a:struct.unpack_from(fmt,s.image,a-EB)
    record=0x8cd725e8;pid,*pos=read('<i3f',record);assert pid==72
    node=s.words(0x8c109bf8+pid*4)[0]
    kind,flags,mesh=read('<HHI',node);assert kind==6 and not any(s.words(node+60,2))
    matrix=nl.mmul(nl.placement_matrix(pos,read('<3i',record+16)),
        nl.mmul(nl.placement_matrix(read('<3f',node+12),read('<3i',node+24)),nl.mscale(*read('<3f',node+36))))
    vb,pb,nv,np=read('<IIHH',mesh);triangles=[]
    for i in range(np):
        ip,fl,mask,surf=read('<IIHH',pb+i*36+24);n=fl&65535;ids=read('<'+'h'*(n+2),ip)
        wind=bool(fl&0x40000000)
        for k in range(n):
            indices=(ids[k],ids[k+1],ids[k+2]) if wind else (ids[k],ids[k+2],ids[k+1])
            xyz=[c for v in indices for c in nl.xform(matrix,read('<3f',vb+v*12))]
            triangles.append((*xyz,surf,mask,int(bool(fl&0x80000000))|(0 if wind else 2),1));wind=not wind
    return pos,triangles

def generate(out,baseline_path=None):
    from kogane_collision import command
    s=Source(2);tm=json.loads((DC/'stage2_texmap.json').read_text())
    root=s.words(0x8c109728+72*4)[0];mapping=tm['texmap'][str(root-SB)]
    assert mapping==[241]
    textures=out/'textures.bin';textures.write_bytes(b''.join((DC/p).read_bytes() for p in tm['packs']))
    roots=[root,s.words(0x8c109990+72*4)[0]]
    specs=[f'cover{i}:afs/STAGE2/000_st2dat.bin:{textures}:0,0,0,0:rawat:{SB:x}:{r:x}:0:tex=241:lighting=1:cull=none' for i,r in enumerate(roots)]
    subprocess.run([sys.executable,'tools/jgc_convert.py',str(out/'kogane_cover.jgc'),'--motions=0','--texmax=512','--source-material=1','--source-environment=1',*specs],cwd=DC,check=True)
    full=out/'full.col';subprocess.run([a for a in command(full) if not a.startswith('--dynexclude')],cwd=DC,check=True)
    source=full.read_bytes();count,offset=struct.unpack_from('<II',source,4)
    _,world,np,ne=struct.unpack_from('<4I',source,offset);end=offset+16+1028*4+np*32+ne*12
    signature,owners,_,_=struct.unpack_from('<4I',source,end);assert signature==0x31504943
    wanted={r['address'] for r in removed_records()};opened=[];found=set()
    # Retain the previously shipped contact orientation for the removed
    # construction bodies; every unrelated static triangle stays untouched.
    baseline=Path(baseline_path or DC/'campaign_captures/kogane_doors_20260916/baseline_stage2.col').read_bytes()
    for i in range(owners):
        address,kind,first,n=struct.unpack_from('<4I',source,end+16+i*16)
        if address in wanted:
            found.add(address)
            opened.extend(struct.unpack_from('<9f4H',baseline,16+j*44) for j in range(first,first+n))
    assert found==wanted
    pos,closed=cover_triangles()
    def floats(values):return '{'+','.join(float(v).hex()+'f' for v in values)+'}'
    lines=['/* Original sector 22 variants, generated by kogane_cover_assets.py. */',
           'static const float cover_position[3]='+floats(pos)+';']
    lines+=['static const float cover_lights[114][8]={']
    lines+=['    '+floats(struct.unpack_from('<8f',s.exe,0x8c17c580+i*32-EB))+',' for i in range(114)]
    lines+=['};']
    for name,rows in [('cover_closed',closed),('cover_open',opened)]:
        lines+=['static const ColTri '+name+'[]={']
        lines+=['    {'+floats(r[:9])+','+','.join(map(str,r[9:]))+'},' for r in rows]
        lines+=['};']
    (out/'kogane_cover_data.inc').write_text('\n'.join(lines)+'\n')
    (out/'kogane_cover.json').write_text(json.dumps(dict(sector=22,mission_word=224,mask=1,record=hex(0x8cd725e8),root=hex(root),texture=241,position=pos,closed_triangles=len(closed),open_triangles=len(opened),removed_records=sorted(wanted)),indent=2)+'\n')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');parser.add_argument('--baseline',type=Path,help='Regenerated original contact context');args=parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='jgr-cover-') as tmp:
        out=Path(tmp);generate(out,args.baseline)
        for name in ('kogane_cover.jgc','kogane_cover.json','kogane_cover_data.inc'):
            target=ROOT/'psp'/('src' if name.endswith('.inc') else '')/name
            if args.check:assert target.read_bytes()==(out/name).read_bytes(),name
            else:target.write_bytes((out/name).read_bytes())
