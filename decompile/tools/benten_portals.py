#!/usr/bin/env python3
"""Recover all four Benten passage records registered by 8c032308."""
from pathlib import Path
import argparse
import struct

ROOT = Path(__file__).resolve().parents[2]
FIRST = 0x8c177d60

def generate(first=FIRST, name='benten', tool='benten_portals.py', count=4):
    data = (ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes()
    lines = [f'/* Generated by {tool} from 1ST_READ.BIN; do not edit. */',
             f'static const StagePortal {name}_portals[{count}] = {{']
    for address in range(first, first+count*0x70, 0x70):
        f = struct.unpack_from('<28f', data, address-0x8c010000)
        assert f[24:] == (0.,)*4
        vec = lambda a: '{'+','.join(x.hex()+'f' for x in a)+'}'
        lines += [f'    {{ /* {address:08x} */',
                  '        '+vec(f[:3])+','+vec(f[3:6])+',',
                  '        {'+','.join(vec(f[i:i+3]) for i in range(6,18,3))+'},',
                  '        '+vec(f[18:21])+','+vec(f[21:24]), '    },']
    return '\n'.join(lines+['};',''])

if __name__ == '__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    path=ROOT/'psp/src/benten_portals.inc';text=generate()
    if args.check:
        assert path.read_text()==text, 'Benten portals differ from original executable'
    else:path.write_text(text)
