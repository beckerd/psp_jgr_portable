#!/usr/bin/env python3
"""Original 03a1cc water volumes/returns and 0edbec splash model/motion."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
import tempfile

ROOT=Path(__file__).resolve().parents[2]
DEC=ROOT/'decompile'

def products(directory):
    exe=(DEC/'extracted/1ST_READ.BIN').read_bytes()
    read=lambda fmt,a:struct.unpack_from('<'+fmt,exe,a-0x8c010000)
    lines=['/* Generated by kogane_water_assets.py; original 03a1cc / 0c7ff4. */',
           'static const WaterReturn KOGANE_WATER_RETURN[3]={']
    volumes=[];groups=[]
    for table,payload in [(0x8c17c504,0x8c17c4e0),(0x8c17c54c,0x8c17c528),(0x8c17c578,0x8c17c554)]:
        values=read('6f3i',payload)
        lines.append('    {{%s},{%s},{%s}},'%(','.join(v.hex()+'f' for v in values[:3]),
            ','.join(v.hex()+'f' for v in values[3:6]),','.join(map(str,values[6:]))))
        addresses=[]
        for j in range(20):
            a=read('I',table+4*j)[0]
            if not a:break
            addresses.append(a);volumes.append(read('36f',a))
        else:raise ValueError('unterminated water list')
        groups.append(dict(table=hex(table),payload=hex(payload),volumes=list(map(hex,addresses)),return_data=values))
    lines+=['};','static const WaterVolume KOGANE_WATER_VOLUME[10]={']
    assert len(volumes)==10
    for v in volumes:
        points=','.join('{'+','.join(x.hex()+'f' for x in v[j:j+3])+'}' for j in range(0,18,3))
        normals=','.join('{'+','.join(x.hex()+'f' for x in v[j:j+3])+'}' for j in range(18,36,3))
        lines.append('    {{%s},{%s}},'%(points,normals))
    lines+=['};','static const float KOGANE_WATER_HEIGHT[6]={'+','.join(v.hex()+'f' for v in read('6f',0x8c1e10f8))+'};','']
    header='\n'.join(lines)
    dat='afs/PLAYER/016_player_effect_dat.bin';txr='afs/PLAYER/017_player_effect_txr.bin'
    root=read('I',0x8c182fe8+0x9c)[0];motion=read('I',0x8c18308c+0x9c)[0]
    source=(DEC/dat).read_bytes()
    assert struct.unpack_from('<H',source,motion-0x8c8e1000+2)[0]==41
    row=f'WaterSplash:{dat}:{txr}:0,0,0,0:rawat:8c8e1000:{root:x}:{motion:x}:lighting=1'
    path=directory/'watersplash.jgc'
    subprocess.run([sys.executable,'tools/jgc_convert.py',str(path),'--motions=1',
                    '--source-material=1','--source-environment=1',row],cwd=DEC,check=True)
    manifest=dict(groups=groups,splash=dict(root=hex(root),motion=hex(motion),frames=41,scale=2,
        source_sha256=hashlib.sha256(source).hexdigest(),
        texture_sha256=hashlib.sha256((DEC/txr).read_bytes()).hexdigest(),
        sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
    return header,json.dumps(manifest,indent=2)+'\n'

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    if args.check:
        with tempfile.TemporaryDirectory() as temp:
            directory=Path(temp);header,manifest=products(directory)
            assert (directory/'watersplash.jgc').read_bytes()==(ROOT/'psp/watersplash.jgc').read_bytes()
            assert header==(ROOT/'psp/src/kogane_water_data.inc').read_text()
            assert manifest==(ROOT/'psp/kogane_water_assets.json').read_text()
    else:
        header,manifest=products(ROOT/'psp')
        (ROOT/'psp/src/kogane_water_data.inc').write_text(header)
        (ROOT/'psp/kogane_water_assets.json').write_text(manifest)

if __name__=='__main__':main()
