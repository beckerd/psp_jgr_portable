#!/usr/bin/env python3
"""Extract logical-motion descriptors and their actual PLAY clips.

The descriptor's +8/+12 fields index the animation-reference table, NOT
another logical-motion descriptor. JGC frame counts come from PLAY headers.
"""
from pathlib import Path
import struct
import sys

ROOT=Path(__file__).resolve().parents[2]
def generate(exe,jgc):
    def u(a): return struct.unpack_from('<I',exe,a-0x8c010000)[0]
    def f(a): return struct.unpack_from('<f',exe,a-0x8c010000)[0]
    h=struct.unpack_from('<16I',jgc,4)
    counts=[]
    for c in range(16):
        _,_,start,n=struct.unpack_from('<4I',jgc,h[7]+c*48)
        counts.append([struct.unpack_from('<I',jgc,h[13]+8*(start+i))[0] for i in range(n)])
    model_of_char=(4,6,3,2,1,7,10,0,15,8,13,11,12,5,9,14)
    def clip(ref):
        if ref==0xffffffff:return (-1,0,-1,0)
        a=0x8c10a808+ref*16
        anim=u(a)
        return anim,u(a+8),struct.unpack_from('<i',exe,a+4-0x8c010000)[0],u(a+12)
    lines=['/* Generated by decompile/tools/player_motion.py from 1ST_READ + PLAY/JGC. */',
           '#define PLAYER_MOTION_COUNT 134',
           'static const MotionSpec MOTION_SPEC[PLAYER_MOTION_COUNT][2] = {']
    for i in range(134):
        row=[]
        for mirror in range(2):
            a=0x8c10b2a8+i*64+mirror*32
            entry=clip(u(a+8));end=clip(u(a+12))
            row.append('{'+','.join(map(str,(u(a),*entry,*end,u(a+20),u(a+28))))+','+f(a+4).hex()+'f,'+f(a+24).hex()+'f,'+f(a+16).hex()+'f}')
        lines.append('    {'+','.join(row)+'}, /* logical '+str(i)+' */')
    # +5dc overlays call 0207a8 directly: these are ANIMATION REFERENCES,
    # not indexes into the separate 134-entry logical-motion graph.
    nrefs=(0x8c10b2a8-0x8c10a808)//16
    assert nrefs==170
    lines+=['};',f'#define PLAYER_REFERENCE_COUNT {nrefs}',
            'static const short PLAYER_ANIMATION_REFS[PLAYER_REFERENCE_COUNT][4] = {']
    for ref in range(nrefs):
        a=0x8c10a808+ref*16
        values=struct.unpack_from('<4i',exe,a-0x8c010000)
        assert 0<=values[0]<176 and -1<=values[1]<176 and values[2] in (0,1)
        lines.append('    {'+','.join(map(str,values))+'}, /* reference '+str(ref)+' */')
    lines+=['};','static const short LOCOMOTION_CLIPS[62][2] = {']
    for ref in range(62):
        a=0x8c10a808+ref*16
        lines.append('    {'+str(u(a))+','+str(struct.unpack_from('<i',exe,a+4-0x8c010000)[0])+'},')
    lines+=['};','static const unsigned short PLAYER_CLIP_FRAMES[16][176] = {']
    for model in model_of_char:
        assert len(counts[model])==176
        lines.append('    {'+','.join(map(str,counts[model]))+'},')
    lines+=['};','static const int PLAYER_LOW_HEALTH[16] = {'+
            ','.join(str(u(u(0x8c182884+4*i)+0x1c)) for i in range(16))+'};',
            'static const float MOTION_BLEND_CURVE[2][11] = {']
    for a in (0x8c17e91c,0x8c17e9a0):
        lines.append('    {'+','.join(f(a+12*i).hex()+'f' for i in range(11))+'},')
    lines+=['};','static const unsigned SPRAY_MOTION_MASK[11] = {'+
            ','.join(hex(u(0x8c17e710+4*i))+'u' for i in range(11))+'};',
            'static const unsigned char SPRAY_STYLE_MOTION[17][11] = {']
    for i in range(17):
        a=u(0x8c17e6cc+4*i)
        values=[u(a+4*j) for j in range(11)]
        assert all(v<134 for v in values)
        lines.append('    {'+','.join(map(str,values))+'},')
    return '\n'.join(lines+['};',''])

if __name__=='__main__':
    result=generate((ROOT/'decompile/extracted/1ST_READ.BIN').read_bytes(),(ROOT/'psp/chars.jgc').read_bytes())
    if '--check' in sys.argv:
        assert (ROOT/'psp/src/player_motion.inc').read_text()==result
        print('Logical motion descriptors/PLAY lengths verified for all 16 skaters')
    else: print(result,end='')
