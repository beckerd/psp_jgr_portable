#!/usr/bin/env python3
"""0961b8 enemy sound selectors and original sample/sequence banks."""
import argparse,struct,re
from pathlib import Path
from event_audio_assets import resolve
from cutscene_sources import ROOT,afs_file

def generated():
    cues=[];files={}
    for kind in range(25):
        try:first=resolve(1,0x29,0,kind<<16)
        except (ValueError,AssertionError):continue
        data=afs_file('E_SND_SE',first[0]).read_bytes();count=struct.unpack_from('<I',data,12)[0]
        for program in range(count):
            ref=(kind<<16)|program
            try:r=resolve(1,0x29,0,ref)
            except (ValueError,AssertionError):continue
            cues.append((ref,r));files[r[0]]=data
    for program in (7,8,9,11,15,16,17):
        ref=0xffff0000|program;r=resolve(1,0x29,0,ref);cues.append((ref,r))
        for f in (r[0],r[5]):files[f]=afs_file('E_SND_SE',f).read_bytes()
    lines=['/* Generated by enemy_audio_assets.py from 0961b8 / 1ba590. */','static const EventAudioCue ENEMY_AUDIO_CUES[]={']
    for ref,r in cues:lines.append('    {0x29,0,0x%xu,%s,{%d,%.9gf,%.9gf,%.9gf}},'%(ref,','.join(str(x) for x in r[:7]),r[2],*r[7:]))
    lines+=['};',''];text=re.sub(r'(?<=[,{])(-?[0-9]+)f(?=[,}])',r'\1.f','\n'.join(lines))
    payload=bytearray();header=bytearray(struct.pack('<4sI',b'CAS1',len(files)));offset=8+32*len(files)
    for file,data in sorted(files.items()):
        header.extend(struct.pack('<16s4I',b'E_SND_SE',file,offset+len(payload),len(data),0));payload.extend(data)
    return text,header+payload
if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args();text,bank=generated()
    for path,data in [(ROOT/'psp/src/enemy_audio_tables.inc',text.encode()),(ROOT/'psp/enemyaudio.bin',bank)]:
        if a.check:assert path.read_bytes()==data,path
        else:path.write_bytes(data)
    print('Enemy audio selectors and original banks verified:',len(bank),'bytes')
