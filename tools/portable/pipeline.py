def order(nodes):
    by={n.name:n for n in nodes}
    if len(by)!=len(nodes):raise ValueError('Duplicate pipeline node')
    result=[];done=set()
    while len(result)<len(nodes):
        ready=[n for n in nodes if n.name not in done and set(n.after)<=done]
        if not ready:raise ValueError('Unknown dependency or cycle in asset graph')
        for n in ready:result.append(n);done.add(n.name)
    return result

def seed_sources(repo:Path,tree:Path):
    dec=tree/'decompile';(tree/'psp/src').mkdir(parents=True,exist_ok=True)
    shutil.copytree(repo/'decompile/tools',dec/'tools',ignore=shutil.ignore_patterns('__pycache__','*.pyc'))
    shutil.copyfile(Path(__file__).with_name('stage_layout.py'),dec/'tools/portable_stage_layout.py')
    for path in (repo/'psp/src').glob('*.c'):
        shutil.copyfile(path,tree/'psp/src'/path.name)
    for name in ('stage_texture_usage.inc','stage_depth_data.inc'):
        shutil.copyfile(repo/'psp/src'/name,tree/'psp/src'/name)
    for name in SPECS:shutil.copyfile(repo/'decompile'/name,dec/name)

def run(tree:Path,logs:Path,nodes,only=None):
    logs.mkdir(parents=True,exist_ok=True);results={}
    selected=set(only or [n.name for n in nodes])
    unknown=selected-{n.name for n in nodes}
    if unknown:raise ValueError('Unknown conversion targets: '+', '.join(sorted(unknown)))
    # Selecting a target always includes its transitive prerequisites.
    while True:
        more={d for n in nodes if n.name in selected for d in n.after}-selected
        if not more:break
        selected|=more
    for node in order(nodes):
        if node.name not in selected:continue
        missing=[p for p in node.requires if not (tree/p).is_file()]
        failed=[d for d in node.after if results.get(d,{}).get('status')!='ok']
        if missing or failed:
            results[node.name]=dict(status='blocked',missing_inputs=missing,failed_dependencies=failed);continue
        print('Converting '+node.name,flush=True)
        log=logs/(node.name+'.log');error=None
        with log.open('w') as stream:
            for cmd in node.commands:
                stream.write(json.dumps(cmd)+'\n');stream.flush()
                completed=subprocess.run(cmd,cwd=tree/'decompile',stdout=stream,stderr=subprocess.STDOUT)
                if completed.returncode: error=f'Exporter exited {completed.returncode}';break
        missing=[p for p in node.outputs if not (tree/p).is_file()]
        results[node.name]=dict(status='failed' if error or missing else 'ok',commands=node.commands,log=str(log),missing_outputs=missing)
        if error:results[node.name]['error']=error
    return results
