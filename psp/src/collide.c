/* Return 1 for indexed workspace, 0 for the ordinary triangle path, or
   -8 for malformed topology. No caller-owned array is retained for access
   between calls; pointer values participate only in the cache identity. */
static int world_indexed_prepare(Collision *c,const ColWorldIndexedPart *parts,unsigned count)
{
    unsigned vertices=0,mask_words=0;
    for(unsigned p=0;p<count;p++)if(parts[p].triangle_count) {
        if(!parts[p].indices)return 0;
        if(!parts[p].vertices || !parts[p].vertex_count)return -8;
        if(parts[p].vertex_count>(COL_WORLD_INDEXED_BYTES-sizeof(ColWorldIndexed))/8-vertices)return 0;
        vertices+=parts[p].vertex_count;
        mask_words+=(parts[p].vertex_count+31)/32;
    }
    unsigned bytes=sizeof(ColWorldIndexed)+vertices*8+mask_words*sizeof(uint32_t);
    if(bytes>COL_WORLD_INDEXED_BYTES)return 0;
    ColWorldIndexed *g=c->world_indexed;
    if(!g || bytes>g->bytes) {
        ColWorldIndexed *next=malloc(bytes);
        if(!next){world_indexed_release(c);return 0;}
        memset(next,0,sizeof *next);next->bytes=bytes;
        world_indexed_release(c);c->world_indexed=g=next;world_indexed_resident+=bytes;
    }
    int changed=g->count!=count;
    for(unsigned p=0;p<count;p++) {
        const ColWorldIndexedPart *a=parts+p,*b=g->key+p;
        if(a->vertices!=b->vertices || a->indices!=b->indices || a->triangle_count!=b->triangle_count ||
           a->vertex_count!=b->vertex_count || a->topology!=b->topology)changed=1;
    }
    if(!changed)return 1;
    g->count=g->stable_valid=g->mask_valid=0;g->used=(unsigned *)(g+1);g->cell=g->used+vertices;
#if JGR_COLLISION_DIRTY_TRIANGLES
    world_dirty_release(g);
#endif
    g->stable_masks=(uint32_t *)(g->cell+vertices);
    unsigned base=0,mask_base=0;
    for(unsigned p=0;p<count;p++) {
        const ColWorldIndexedPart *part=parts+p;
        g->vertex_offset[p]=base;g->used_count[p]=0;g->key[p]=*part;
        g->mask_offset[p]=mask_base;
        if(!part->triangle_count)continue;
        memset(g->cell+base,255,part->vertex_count*sizeof(unsigned));
        for(unsigned i=0;i<part->triangle_count*3;i++) {
            unsigned v=part->indices[i];
            if(v>=part->vertex_count)return -8;
            if(g->cell[base+v]==~0u){g->cell[base+v]=0;g->used[base+g->used_count[p]++]=v;}
        }
        base+=part->vertex_count;
        mask_base+=(part->vertex_count+31)/32;
    }
#if JGR_COLLISION_DIRTY_TRIANGLES
    world_dirty_prepare(g,parts,count,vertices);
#endif
    g->count=count;return 1;
}
static unsigned world_phase_end(unsigned phase,unsigned start)
{
    unsigned now=collision_clock(),elapsed=now-start;
    if(!phase)collision_profile.grid_bounds_us+=elapsed;
    else if(phase==1)collision_profile.grid_copy_us+=elapsed;
    else collision_profile.grid_update_us+=elapsed;
    return now;
}
static int world_unchanged(const uint32_t *bits,unsigned at)
{return bits && (bits[at/32]&(1u<<(at%32)));}
static int world_copy_parts(Collision *c,const ColWorldIndexedPart *parts,unsigned count,int n,
                            const ColWorldStability *stable,const unsigned valid[2])
{
    geometry_forget(c);world_grid_disable(c);
    if(n>c->cap){ColTri *t=realloc(c->tri,n*sizeof(ColTri));if(!t)return -2;c->tri=t;c->cap=n;}
    source_free(c->source);c->source=NULL;items_free(c->items);c->items=NULL;
    unsigned offset=0;
    for(unsigned p=0;p<count;p++)if(parts[p].triangle_count) {
        const uint32_t *unchanged=stable && valid[p] ? stable[p].triangles:NULL;
        if(!unchanged)memcpy(c->tri+offset,parts[p].triangles,parts[p].triangle_count*sizeof(ColTri));
        else for(unsigned i=0;i<parts[p].triangle_count;) {
            if(world_unchanged(unchanged,i)){collision_profile.grid_unchanged_triangles++;i++;continue;}
            unsigned first=i++;
            while(i<parts[p].triangle_count && !world_unchanged(unchanged,i))i++;
            memcpy(c->tri+offset+first,parts[p].triangles+first,(i-first)*sizeof(ColTri));
        }
        offset+=parts[p].triangle_count;
    }
    free(c->alias);c->alias=NULL;c->alias16=c->alias_cap=0;
    c->ntri=c->nbase=c->ngeom=c->nbase_geom=n;return 0;
}
static int world_publish_parts(Collision *c,const ColWorldIndexedPart *parts,unsigned count,int indexed,const ColWorldStability *stable)
{
    if(!c || !parts || !count || count>2)return -1;
    unsigned total=0;
    for(unsigned p=0;p<count;p++) {
        if(parts[p].triangle_count>(unsigned)INT_MAX/sizeof(ColTri)-total ||
           (parts[p].triangle_count && !parts[p].triangles))return -1;
        total+=parts[p].triangle_count;
    }
    if(!total)return -1;
    int n=(int)total;unsigned stamp=collision_clock(),phase=0;
    if(indexed){indexed=world_indexed_prepare(c,parts,count);if(indexed<0)return indexed;}
    if(!indexed)world_indexed_release(c);
    unsigned stable_valid[2]={0,0};
#if JGR_COLLISION_CELL_REUSE || JGR_COLLISION_DIRTY_TRIANGLES
    unsigned previous_cells=0;
#endif
    if(indexed) {
        ColWorldIndexed *g=c->world_indexed;
#if JGR_COLLISION_CELL_REUSE || JGR_COLLISION_DIRTY_TRIANGLES
        /* Preparation clears stable_valid on topology/pointer changes.
           A foreign publisher disables the old grid. Generation gaps still
           allow exact new-code comparison; they never authorize skipping
           coordinate evaluation through the separate stability proof. */
        previous_cells=g->stable_valid && world_grid_active(c) && c->ntri==n &&
            !c->source && !c->items && !c->alias;
#endif
        for(unsigned p=0;p<count;p++)stable_valid[p]=stable && g->stable_valid && world_grid_active(c) &&
            c->ntri==n && !c->source && !c->items && !c->alias &&
            stable[p].generation && g->generation[p] && g->generation[p]!=UINT_MAX &&
            stable[p].generation==g->generation[p]+1;
        /* Every early error invalidates proofs even while the old owned
           world remains queryable. Successful publication re-arms them. */
        g->stable_valid=0;
    }
    /* First-reference order is the original triangle-corner order with only
       repetitions removed. Unused (including inactive/uninitialized) points
       cannot change validity, min/max, origin, or membership. */
    float x0=1e9f,z0=1e9f,x1=-1e9f,z1=-1e9f;int sentinel=0;
    for(unsigned p=0;p<count;p++) {
        const ColWorldIndexedPart *part=parts+p;
        if(!part->triangle_count)continue;
        ColWorldIndexed *g=indexed ? c->world_indexed:NULL;
        const uint32_t *mask=indexed && stable ? stable[p].vertices:NULL;
        unsigned mask_bytes=((part->vertex_count+31)/32)*sizeof(uint32_t);
        int cached=mask && stable_valid[p] && (g->mask_valid&(1u<<p)) &&
            !memcmp(mask,g->stable_masks+g->mask_offset[p],mask_bytes);
        float bound[4]={1e9f,-1e9f,1e9f,-1e9f};
        if(cached) {
            memcpy(bound,g->stable_bounds[p],sizeof bound);
            if(bound[0]<x0)x0=bound[0];if(bound[1]>x1)x1=bound[1];
            if(bound[2]<z0)z0=bound[2];if(bound[3]>z1)z1=bound[3];
        }
        unsigned used=indexed ? c->world_indexed->used_count[p]:part->triangle_count*3;
        for(unsigned i=0;i<used;i++) {
            unsigned vertex=indexed ? g->used[g->vertex_offset[p]+i]:0;
            int unchanged=world_unchanged(mask,vertex);
            if(cached && unchanged){collision_profile.grid_unchanged_vertices++;continue;}
            const float *v=indexed ? part->vertices+vertex*3:
                part->triangles[i/3].v+(i%3)*3;
            float x=v[0],y=v[1],z=v[2];
            if(!world_finite(x) || !world_finite(y) || !world_finite(z))return -8;
            if(x<x0)x0=x;if(x>x1)x1=x;if(z<z0)z0=z;if(z>z1)z1=z;
            if(indexed && (x<-1e9f || x>1e9f || z<-1e9f || z>1e9f))sentinel=1;
            if(unchanged) {
                if(x<bound[0])bound[0]=x;if(x>bound[1])bound[1]=x;
                if(z<bound[2])bound[2]=z;if(z>bound[3])bound[3]=z;
            }
        }
        if(mask) {
            if(!cached){memcpy(g->stable_bounds[p],bound,sizeof bound);memcpy(g->stable_masks+g->mask_offset[p],mask,mask_bytes);}
            g->mask_valid|=1u<<p;
        } else if(g)g->mask_valid&=~(1u<<p);
    }
    /* The legacy per-triangle min/max has +/-1e9 seeds. Keep that exact
       behavior for extreme coordinates instead of deriving only vertex cells. */
    if(sentinel)indexed=0;
    x0-=1.f;z0-=1.f;
    double width=((double)x1-x0)/128.f+1,height=((double)z1-z0)/128.f+1;
    if(!isfinite(width) || !isfinite(height) || width<1 || height<1 || width>65535 || height>65535 || n>65536)goto fallback;
    int gw=(int)width,gh=(int)height;unsigned words=((unsigned)n+31)/32;
    size_t cells=(size_t)gw*gh,rect_bytes=(size_t)n*8;
    if(rect_bytes>COL_WORLD_GRID_BYTES-sizeof(ColWorldGrid) ||
       cells>(COL_WORLD_GRID_BYTES-sizeof(ColWorldGrid)-rect_bytes)/(words*sizeof(unsigned)))goto fallback;
    stamp=world_phase_end(phase,stamp);phase=1;
    unsigned bytes=(unsigned)(sizeof(ColWorldGrid)+rect_bytes+cells*words*sizeof(unsigned));
    ColWorldGrid *g=c->world_grid;
    if(!g || bytes>g->bytes) {
        ColWorldGrid *next=malloc(bytes);if(!next)goto fallback;
        memset(next,0,sizeof *next);next->bytes=bytes;
        world_grid_release(c);c->world_grid=g=next;world_grid_resident+=bytes;
    }
    int rebuild=!g->active || g->n!=n || g->gw!=gw || g->gh!=gh;
    int same_origin=!rebuild && c->x0==x0 && c->z0==z0 && c->gw==gw && c->gh==gh;
    if(world_copy_parts(c,parts,count,n,indexed ? stable:NULL,stable_valid))goto fallback;
    c->cell=128.f;c->x0=x0;c->z0=z0;c->gw=gw;c->gh=gh;c->index16=n<=65536;
    stamp=world_phase_end(phase,stamp);phase=2;
    g->rect=(unsigned short *)(g+1);g->bits=(unsigned *)((unsigned char *)g->rect+rect_bytes);
    if(rebuild)memset(g->bits,0,cells*words*sizeof(unsigned));
    g->words=words;g->n=n;g->gw=gw;g->gh=gh;g->active=0;
#if JGR_COLLISION_DIRTY_TRIANGLES
    ColWorldDirty *dirty=world_dirty_enabled && indexed && previous_cells && !rebuild ? c->world_indexed->dirty:NULL;
    unsigned dirty_word=0,dirty_pending=0,dirty_visited=0;
    if(dirty){memset(dirty->bits,0,dirty->words*sizeof(unsigned));collision_profile.grid_dirty_publishes++;}
    else if(indexed)collision_profile.grid_dirty_fallbacks++;
#endif
    if(indexed)for(unsigned p=0;p<count;p++) {
        ColWorldIndexed *index=c->world_indexed;unsigned base=index->vertex_offset[p];
        for(unsigned i=0;i<index->used_count[p];i++) {
            unsigned v=index->used[base+i];const float *point=parts[p].vertices+v*3;
            if(same_origin && stable_valid[p] && world_unchanged(stable[p].vertices,v)) {
#if JGR_COLLISION_CELL_REUSE
                index->cell[base+v]|=WORLD_CELL_SAME;
                collision_profile.grid_cell_code_same++;
#endif
                collision_profile.grid_unchanged_cells++;continue;
            }
            float x=(point[0]-x0)*(1.f/128.f),z=(point[2]-z0)*(1.f/128.f);
            if(!(x>=0 && x<gw && z>=0 && z<gh)){col_free(c);return -8;}
            unsigned code=(unsigned)(int)x | ((unsigned)(int)z<<16);
#if JGR_COLLISION_DIRTY_TRIANGLES
            unsigned old_code=index->cell[base+v];
#if JGR_COLLISION_CELL_REUSE
            old_code&=~WORLD_CELL_SAME;
#endif
            if(dirty && code!=old_code)world_dirty_mark(dirty,base+v);
#endif
#if JGR_COLLISION_CELL_REUSE
            if(previous_cells && !rebuild && code==(index->cell[base+v]&~WORLD_CELL_SAME)) {
                code|=WORLD_CELL_SAME;collision_profile.grid_cell_code_same++;
            }
#endif
            index->cell[base+v]=code;
        }
    }
    unsigned part_number=0,part_first=0;
    for(int i=0;i<n;i++) {
#if JGR_COLLISION_DIRTY_TRIANGLES
        if(dirty){i=world_dirty_next(dirty,&dirty_word,&dirty_pending);if(i<0)break;dirty_visited++;}
#endif
        unsigned short rect[4];
        if(indexed) {
            while((unsigned)i>=part_first+parts[part_number].triangle_count){part_first+=parts[part_number].triangle_count;part_number++;}
            if(same_origin && stable_valid[part_number] &&
               world_unchanged(stable[part_number].triangles,(unsigned)i-part_first)) {
                collision_profile.grid_reused_rects++;continue;
            }
            const unsigned *ids=parts[part_number].indices+((unsigned)i-part_first)*3;
            const unsigned *coordinates=c->world_indexed->cell+c->world_indexed->vertex_offset[part_number];
            unsigned a=coordinates[ids[0]],b=coordinates[ids[1]],d=coordinates[ids[2]];
#if JGR_COLLISION_CELL_REUSE
            if((a&b&d)&WORLD_CELL_SAME) {
                collision_profile.grid_cell_rect_skips++;collision_profile.grid_reused_rects++;continue;
            }
            a&=~WORLD_CELL_SAME;b&=~WORLD_CELL_SAME;d&=~WORLD_CELL_SAME;
#endif
            unsigned ax=a&65535,bx=b&65535,dx=d&65535,az=a>>16,bz=b>>16,dz=d>>16;
            unsigned lx=ax<bx?ax:bx,hx=ax>bx?ax:bx,lz=az<bz?az:bz,hz=az>bz?az:bz;
            if(dx<lx)lx=dx;if(dx>hx)hx=dx;if(dz<lz)lz=dz;if(dz>hz)hz=dz;
            rect[0]=(unsigned short)lx;rect[1]=(unsigned short)hx;rect[2]=(unsigned short)lz;rect[3]=(unsigned short)hz;
        } else {
            const ColTri *tri=c->tri+i;float lo_x=1e9f,lo_z=1e9f,hi_x=-1e9f,hi_z=-1e9f;
            for(int k=0;k<3;k++) {
                float x=tri->v[k*3],z=tri->v[k*3+2];
                if(x<lo_x)lo_x=x;if(x>hi_x)hi_x=x;if(z<lo_z)lo_z=z;if(z>hi_z)hi_z=z;
            }
            float q[4]={(lo_x-x0)*(1.f/128.f),(hi_x-x0)*(1.f/128.f),
                        (lo_z-z0)*(1.f/128.f),(hi_z-z0)*(1.f/128.f)};
            if(!(q[0]>=0 && q[1]<gw && q[2]>=0 && q[3]<gh)){col_free(c);return -8;}
            rect[0]=(unsigned short)(int)q[0];rect[1]=(unsigned short)(int)q[1];
            rect[2]=(unsigned short)(int)q[2];rect[3]=(unsigned short)(int)q[3];
        }
        collision_profile.grid_rect_evaluated++;
        unsigned short *old=g->rect+i*4;
        if(!rebuild && old[0]==rect[0] && old[1]==rect[1] && old[2]==rect[2] && old[3]==rect[3]){collision_profile.grid_reused_rects++;continue;}
        unsigned word=(unsigned)i>>5,bit=1u<<(i&31);
        if(!rebuild)for(unsigned z=old[2];z<=old[3];z++)for(unsigned x=old[0];x<=old[1];x++)
            g->bits[(z*(unsigned)gw+x)*words+word]&=~bit;
        for(unsigned z=rect[2];z<=rect[3];z++)for(unsigned x=rect[0];x<=rect[1];x++)
            g->bits[(z*(unsigned)gw+x)*words+word]|=bit;
        old[0]=rect[0];old[1]=rect[1];old[2]=rect[2];old[3]=rect[3];collision_profile.grid_changed_rects++;
    }
#if JGR_COLLISION_DIRTY_TRIANGLES
    if(dirty) {
        collision_profile.grid_dirty_visited+=dirty_visited;
        collision_profile.grid_dirty_skipped+=(unsigned)n-dirty_visited;
        collision_profile.grid_reused_rects+=(unsigned)n-dirty_visited;
    }
#endif
    g->active=1;collision_profile.grid_publishes++;collision_profile.grid_rebuilds+=rebuild;
    if(indexed) {
        c->world_indexed->stable_valid=1;
        for(unsigned p=0;p<count;p++)c->world_indexed->generation[p]=stable ? stable[p].generation:0;
    }
    collision_profile.grid_indexed_publishes+=indexed;world_phase_end(phase,stamp);return 0;
fallback:
    world_phase_end(phase,stamp);collision_profile.grid_fallbacks++;
    /* Release optional storage before the legacy retry. The packed builder
       consumes the directly copied spans, so no intermediate joined array is
       needed even when an optional allocation fails. */
    world_grid_release(c);world_indexed_release(c);stamp=collision_clock();
    int error=world_copy_parts(c,parts,count,n,NULL,NULL);stamp=world_phase_end(1,stamp);
    if(!error)error=build_grid(c);
    world_phase_end(2,stamp);
    if(error)col_free(c);return error;
}
