/* Immutable compact vertex -> logical triangle adjacency. A changed packed
   cell marks precisely the incident contacts; triangle IDs remain ascending
   when consumed. This changes only which rectangles are recomputed, never
   owned geometry, cell arithmetic, query order or the stability contract. */
static void world_dirty_prepare(ColWorldIndexed *g,const ColWorldIndexedPart *parts,unsigned count,unsigned vertices)
{
    world_dirty_release(g);
    unsigned triangles=0;
    for(unsigned p=0;p<count;p++) {
        if(parts[p].triangle_count>65535u/3-triangles)return;
        triangles+=parts[p].triangle_count;
    }
    unsigned refs=triangles*3,words=(triangles+31)/32;
    size_t bytes=sizeof(ColWorldDirty)+words*sizeof(unsigned)+((size_t)vertices+1+refs)*sizeof(unsigned short);
    if(bytes>COL_WORLD_DIRTY_BYTES)return;
    ColWorldDirty *d=malloc(bytes);if(!d)return;
    d->bytes=(unsigned)bytes;d->words=words;d->bits=(unsigned *)(d+1);
    d->start=(unsigned short *)(d->bits+words);d->triangle=d->start+vertices+1;
    /* Topology changes invalidate the preceding cells already. Reuse that
       scratch while building CSR, before the mandatory full publication. */
    memset(g->cell,0,vertices*sizeof(unsigned));
    for(unsigned p=0;p<count;p++)for(unsigned i=0;i<parts[p].triangle_count*3;i++)
        g->cell[g->vertex_offset[p]+parts[p].indices[i]]++;
    unsigned at=0;
    for(unsigned v=0;v<vertices;v++){unsigned degree=g->cell[v];d->start[v]=(unsigned short)at;g->cell[v]=at;at+=degree;}
    d->start[vertices]=(unsigned short)at;
    unsigned first=0;
    for(unsigned p=0;p<count;p++) {
        for(unsigned i=0;i<parts[p].triangle_count;i++)for(unsigned k=0;k<3;k++) {
            unsigned v=g->vertex_offset[p]+parts[p].indices[i*3+k];
            d->triangle[g->cell[v]++]=(unsigned short)(first+i);
        }
        first+=parts[p].triangle_count;
    }
    g->dirty=d;world_dirty_resident+=d->bytes;collision_profile.grid_dirty_builds++;
}
static void world_dirty_mark(ColWorldDirty *d,unsigned vertex)
{
    for(unsigned i=d->start[vertex],end=d->start[vertex+1];i<end;i++) {
        unsigned triangle=d->triangle[i];d->bits[triangle>>5]|=1u<<(triangle&31);
    }
}
static int world_dirty_next(const ColWorldDirty *d,unsigned *word,unsigned *pending)
{
    while(!*pending){if(*word>=d->words)return -1;*pending=d->bits[(*word)++];}
    unsigned bit=(unsigned)__builtin_ctz(*pending);*pending&=*pending-1;
    return (int)((*word-1)*32+bit);
}
