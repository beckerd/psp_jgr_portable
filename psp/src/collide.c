static int collision_grid_cell(float point,float origin,float cell,int count)
{
    /* All runtime grids use 128-unit cells. A power-of-two scale is exact;
       only subtraction rounds. Keep the double path at integer boundaries
       (or extreme values), preserving the exact original candidate order. */
#ifndef JGR_GRID_CELL_REFERENCE
    if(cell==128.f) {
        float q=(point-origin)*(1.f/128.f);
        float error=(fabsf(point)+fabsf(origin))*(2.f*FLT_EPSILON/128.f)+1e-6f;
        if(isfinite(q) && isfinite(error) && error<.25f) {
            if(q+error<0.f)return -1;
            if(q-error>=(float)count)return count;
            if(q>=0.f && q<(float)count) {
                int lower=(int)q;
                if(q-lower>error && (lower+1.f)-q>error)return lower;
            }
        }
    }
#endif
    double q=((double)point-origin)/cell;
    return q<0 ? -1:q>=count ? count:(int)q;
}
