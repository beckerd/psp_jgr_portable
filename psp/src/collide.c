int col_load(Collision *c, const char *path)
{
    geometry_forget(c);
    memset(c, 0, sizeof *c);
    SceUID fd = sceIoOpen(path, PSP_O_RDONLY, 0777); if (fd < 0) return -1;
    SceOff len = sceIoLseek(fd, 0, PSP_SEEK_END); sceIoLseek(fd, 0, PSP_SEEK_SET);
    unsigned char header[16]; int n, result;
    if (len < 16 || read_exact(fd, header, 16) || memcmp(header, "COL1", 4)) { sceIoClose(fd); return -4; }
    memcpy(&n, header+4, sizeof n);
    if (n <= 0 || n > 0x7fffffff/(int)sizeof(ColTri)-512 || 16+(SceOff)n*sizeof(ColTri) > len) { sceIoClose(fd); return -5; }
    /* Read directly into the owned triangle array. The old full-file staging
       copy added 2.54 MiB to Shibuya's peak and could exhaust PSP-1000 memory,
       silently leaving the entire level without collision. */
    /* 4096 unused triangles cost 176 KiB. A smaller reserve grows on demand;
       no collision is omitted. Shared storage below saves substantially more. */
    c->cap = n+512; c->tri = malloc(c->cap*sizeof(ColTri));
    if (!c->tri) { sceIoClose(fd); c->cap = 0; return -3; }
    result = read_exact(fd, c->tri, n*sizeof(ColTri));
    /* A mis-strided Kogane export previously shipped NaN positions. Never
       feed non-finite coordinates to grid indexing or float-to-int casts. */
    if (!result) for (int i=0;i<n && !result;i++) for (int k=0;k<9;k++)
        if (!isfinite(c->tri[i].v[k])) { result=-8;break; }
    if (!result) {
        c->ntri=c->nbase=c->ngeom=c->nbase_geom=n;share_geometry(c);
        unsigned offset,magic;memcpy(&offset,header+8,4);memcpy(&magic,header+12,4);
        result=source_load(c,fd,offset,magic,len);
        SceOff used=16+(SceOff)n*44;
        if(c->source)used+=4128+c->source->npatch*32+c->source->nentry*12;
        if(!result)result=items_load(c,fd,len-used,c->source?c->source->nworld:0);
        if(!result)result=build_grid(c);
    }
    sceIoClose(fd);
    if (result) col_free(c);
    return result;
}
